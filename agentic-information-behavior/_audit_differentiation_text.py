"""Scratch audit: what does each literature matrix's `differentiation` column actually say, per package.

The sentence is generated by grade_wave_literature.DIFF, which was written while every graded package was a
routing-corpus paper. A row in a transcript-corpus package that claims its contribution is "the measured mechanism on
an agent-instruction corpus with a frozen lexical ranker" is a false statement about its own data, so the shipped text
is read rather than assumed.
"""
import collections
import csv
import glob
import pathlib

for f in sorted(glob.glob("papers/P0*/literature_matrix.csv")):
    pkg = pathlib.Path(f).parts[-2][:4]
    rows = list(csv.DictReader(open(f, encoding="utf-8")))
    lv = collections.Counter(r.get("overlap_level") for r in rows)
    sent = collections.Counter((r.get("differentiation") or "<empty>")[:78] for r in rows)
    print(f"{pkg} {pathlib.Path(f).parts[-2][4:]:42s} rows={len(rows):3d} {dict(lv)}")
    for s, n in sent.most_common(3):
        print(f"      {n:3d} | {s}")
