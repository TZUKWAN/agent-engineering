def nonempty(p: Path) -> bool:
    return p.is_file() and p.stat().st_size > 200


def count_kind(p: Path, suffix: str) -> int:
    return len(list(p.rglob(f"*{suffix}"))) if p.is_dir() else 0


def registry_paper_id_vocabulary(program_dir: Path):
    """EXP-0078: paper_id must be a `P###` package id, `programme`, or a ';' join of those. Before this check the
    column mixed topic ids with paper ids, which made a per-paper query silently return nothing for P002. The
    vocabulary was a literal P001-P005 list until the wave packages opened P006+, at which point a valid new package
    id read as a violation - the check is now the shape the label has, not the five values that happened to exist."""
    import csv as _csv, io as _io, re as _re
    p = program_dir / "experiment_registry.csv"
    rows = list(_csv.DictReader(_io.StringIO(p.read_text(encoding="utf-8"))))
    bad = [r["exp_id"] for r in rows
           if not all(t.strip() == "programme" or _re.fullmatch(r"P[0-9]{3}", t.strip())
                      for t in (r.get("paper_id") or "").split(";") if t.strip())]
    return {"rows": len(rows), "violations": bad}


def audit_paper(pdir: Path) -> dict:
    out = {"paper": pdir.name}
    missing, weak = [], []
    # A premise-blocked design is a recorded decision, not an empty package. Without this branch the audit spends
    # 28 "missing" rows on a topic that was never going to have them; with it the directory is still checked - the
    # BLOCKED.md must name an experiment whose artefact exists on disk - so "blocked" cannot be used to make a
    # package vanish without a trace.
    bl = pdir / "BLOCKED.md"
    if bl.is_file():
        t = bl.read_text(encoding="utf-8", errors="replace")
        cited = sorted(set(re.findall(r"EXP-?(\d{4})", t)))
        evidenced = [e for e in cited if any((ROOT / "results_raw").glob(f"EXP{e}_*"))]
        note = ("premise-blocked; measurement cited: "
                + (", ".join("EXP-" + e for e in evidenced) if evidenced else "NONE ON DISK"))
        if not evidenced:
            weak.append("BLOCKED.md names no experiment with an artefact in results_raw/, so the block is unsupported")
        return {"paper": pdir.name, "blocked": True, "missing": missing, "weak": weak,
                "ready_for_submission_gate": False, "note": note}
    for item, cands in ITEMS.items():
        hit = next((pdir / c for c in cands if (pdir / c).exists()), None)
        if hit is None:
            missing.append(item)
            continue
        if item.endswith("vector)") and count_kind(hit, ".pdf") < 3:
            weak.append(f"{item} ({count_kind(hit, '.pdf')} pdf)")
        elif item.endswith("csv)") and count_kind(hit, ".csv") < 3:
            weak.append(f"{item} ({count_kind(hit, '.csv')} csv)")
        elif item == "claims_evidence_matrix.csv" and not nonempty(hit):
            weak.append(item + " (empty)")
    # Deliverable 16 is a script a reviewer is meant to run, so it has to parse. This check exists because the first
    # version of this audit asked only whether reproduce.sh was present and >200 bytes, and six wave-1 packages
    # shipped one whose command lines each carried an unmatched quotation mark - `bash -n` fails with "unexpected EOF
    # while looking for matching `"'". Existence is not executability, and a verifier that cannot see a requirement
    # does not certify it.
    rs = pdir / "reproduce.sh"
    if rs.is_file():
        _txt = rs.read_text(encoding="utf-8", errors="replace")
        if _txt.count('"') % 2:
            weak.append(f"reproduce.sh: odd number of quotation marks ({_txt.count(chr(34))}), cannot parse")
        else:
            import shutil
            import subprocess
            _bash = shutil.which("bash")
            if _bash:
                _r = subprocess.run([_bash, "-n", str(rs)], capture_output=True, text=True)
                if _r.returncode != 0:
                    weak.append("reproduce.sh fails `bash -n`: " + (_r.stderr or "").strip().replace("\n", " ")[:170])
                else:
                    out["reproduce_syntax"] = "bash -n passed"
            else:
                out["reproduce_syntax"] = "UNVERIFIED: no bash on this machine"
    # A generated table may legitimately be small, but it may not be a sentence saying there are no numbers. The
    # factory now refuses to write one; this catches any that arrived by another route (a stub once shipped in ten
    # of eighteen tables while this audit printed weak=none, because the file existed and had bytes).
    tdir = pdir / "tables"
    if tdir.is_dir():
        for tf in sorted(tdir.glob("*.csv")):
            body = tf.read_text(encoding="utf-8", errors="replace")
            _rows = [r for r in csv.reader(io.StringIO(body))][1:]
            _blank = not _rows or all(not [c for c in r if c.strip()] for r in _rows)
            if "no rows for this table" in body or _blank:
                weak.append(f"{tf.name} carries no measured rows (placeholder or empty table)")

    # §0 defines figures/ as 论文全部图 and §15 gives each figure a role, so two roles drawn from the same table are
    # one figure counted twice. A default branch in the figure dispatcher drew fig4/fig5/fig6 identically in all 13
    # wave packages while this audit still counted three files and reported nothing.
    fdir = pdir / "figures"
    if fdir.is_dir():
        _by = {}
        for _f in sorted(fdir.glob("*.pdf")):
            _by.setdefault(hashlib.sha256(_f.read_bytes()).hexdigest(), []).append(_f.name)
        for _same in _by.values():
            if len(_same) > 1:
                weak.append(f"figures {' + '.join(_same)} are byte-identical: one drawing presented as "
                            f"{len(_same)} of the package's figures")

    # claim-row integrity: an extra cell in a row shifts every later column, so a table name can land in the figure
    # column and the raw result file in where_in_paper while the file itself still looks present. P002's K1 carried 12
    # fields under an 11-column header and the old checks could not see it.
    mfp = pdir / "claims_evidence_matrix.csv"
    if mfp.is_file():
        _rows = [r for r in csv.reader(io.StringIO(mfp.read_text(encoding="utf-8", errors="replace"))) if r]
        _hdr, _body = _rows[0], _rows[1:]
        _bad = [r[0] for r in _body if len(r) != len(_hdr)]
        if _bad:
            weak.append("claims matrix rows with the wrong field count: " + ", ".join(_bad))
        _cols = {c: i for i, c in enumerate(_hdr) if c in ("table", "figure", "raw_result_file")}
        for r in _body:
            if len(r) != len(_hdr):
                continue
            for col, i in _cols.items():
                for part in r[i].split(";"):
                    q = part.strip()
                    if not q or q == "-":
                        continue
                    anchors = [pdir / q, pdir / "tables" / q, pdir / "figures" / q, pdir / "results_raw" / q,
                               pdir / "results_processed" / q, pdir.parent.parent / q]
                    if not any(a.exists() or glob.glob(str(a)) for a in anchors):
                        weak.append(f"{r[0]}: {col} does not resolve to a file ({q[:55]})")

    for md in ("paper.md", "appendix.md", "limitations.md", "reviewer_attack.md", "final_audit.md"):
        f = pdir / md
        if f.is_file():
            t = f.read_text(encoding="utf-8", errors="replace")
            n_words = len(t.split())
            if n_words < 120:
                # `len(t.split)` (uncalled) sat here before EXP-0078: it raised TypeError precisely when a file was
                # short enough to report, so the audit crashed instead of surfacing the weakness
                weak.append(f"{md} very short ({n_words} words)")
    # a configs/ directory that exists but lists no experiments for this paper is the failure mode EXP-0078 found:
    # paper_id was filed under topic ids, so P002's generated config table was empty and still "present"
    cfg = pdir / "configs" / "experiment_configs.csv"
    if cfg.is_file():
        try:
            n_cfg = max(0, len(cfg.read_text(encoding="utf-8").strip().splitlines()) - 1)
        except OSError:
            n_cfg = 0
        if n_cfg == 0:
            weak.append("configs/experiment_configs.csv lists no registered experiments")
    # gate G18-E asks for a clean-environment run; EXP-0079 found P001's record sitting in results_raw where no
    # structural check would look, so the accepted evidence is a normalised environment/clean_room_run_*.json
    _cr = sorted((pdir / "environment").glob("clean_room_run_*.json"),
                 key=lambda f: f.stat().st_mtime)
    if not _cr:
        weak.append("no clean-environment record in environment/ (gate G18-E)")
    else:
        # Existence is not execution: four wave-4 packages shipped a G18-E record whose re-run exited 1 because the
        # script could not find its own input from a scratch directory, and the audit printed weak=none for all four.
        try:
            _crj = json.loads(_cr[-1].read_text(encoding="utf-8", errors="replace"))
        except Exception as exc:                                    # noqa: BLE001 - a corrupt record is a finding
            _crj = {}
            weak.append(f"{_cr[-1].name}: not readable JSON ({type(exc).__name__})")
        code = _crj.get("exit", _crj.get("returncode"))
        if code is None and not (_crj.get("steps_run") or _crj.get("agreement")):
            # P001-P005's records predate the factory and carry their completion evidence as steps/agreement
            # instead of an exit code; anything newer must show the code.
            weak.append(f"{_crj.get('file', _cr[-1].name)}: no exit code and no recorded steps/agreement, so the "
                        f"re-run cannot be shown to have completed")
        elif code not in (None, 0):
            weak.append(f"{_cr[-1].name}: clean-environment re-run exited {code} "
                        f"(tail: {str(_crj.get('stderr_tail') or '')[-160:].strip()})")
        elif code == 0 and not (_crj.get("headline_after_rerun_of_quick_path") or "").strip(' {}"'):
            weak.append(f"{_cr[-1].name}: re-run exited 0 but wrote no headline numbers to compare")
    # gate §18 needs a verdict for EACH of its six sub-gates written in final_audit.md - A data authenticity,
    # B experiment completeness, C statistics, D SOTA discipline, E reproducibility, F writing/claims. A package can
    # list every deliverable and still leave four of the six unaddressed, which is what P002/P004/P005 did.
    fa = pdir / "final_audit.md"
    if fa.is_file():
        _fa_txt = fa.read_text(encoding="utf-8", errors="replace").lower()
        _no_gate = [L for L in "abcdef" if f"g18-{L}" not in _fa_txt]
        if _no_gate:
            weak.append("final_audit.md has no verdict row for G18-" + ", G18-".join(g.upper() for g in _no_gate)
                        + " (spec §18 requires all six)")

    # numbering integrity: a duplicated section id or claim id is the kind of defect a reviewer finds first,
    # and P001 carried two sections numbered L19 until it was checked programmatically
    lf = pdir / "limitations.md"
    if lf.is_file():
        _h = re.findall(r"^## (L\d+)", lf.read_text(encoding="utf-8", errors="replace"), re.M)
        _d = sorted({x for x in _h if _h.count(x) > 1})
        if _d:
            weak.append("duplicate limitations section id(s): " + ", ".join(_d))
    cf = pdir / "claims_evidence_matrix.csv"
    if cf.is_file():
        _ids = [r[0] for r in csv.reader(io.StringIO(cf.read_text(encoding="utf-8", errors="replace"))) if r][1:]
        _cd = sorted({x for x in _ids if _ids.count(x) > 1})
        if _cd:
            weak.append("duplicate claim id(s): " + ", ".join(_cd))

    # Duplicate log rows: a recorder whose idempotency guard tests for a phrase the row it writes never contains
    # appends a second identical entry on every rebuild - EXP-0087's recorder did exactly that (D50 then D51, the
    # guard looking for English text in a Chinese row). Compare the row body with the id and timestamp columns
    # dropped, which are the only two fields that legitimately differ. Split on "|" rather than parsing as CSV:
    # these rows carry quote characters, and a CSV reader swallows everything after one, which collapses unrelated
    # rows to the same key.
    for _lf in ("deviations.md", "reviewer_attack.md"):
        _f = pdir / _lf
        if not _f.is_file():
            continue
        _seen = {}
        for _ln in _f.read_text(encoding="utf-8", errors="replace").splitlines():
            if not _ln.startswith("| ") or set(_ln) <= {"|", "-", " "}:
                continue
            _c = [x.strip() for x in _ln.strip().strip("|").split("|")]
            if len(_c) < 4:
                continue
            _key = "||".join(_c[2:])
            if len(_key) < 80:
                continue
            if _key in _seen:
                weak.append(f"{_lf}: row {_c[0]} repeats the body of {_seen[_key]}")
            else:
                _seen[_key] = _c[0]

    # Duplicate section headings, ignoring the number: a recorder that derives "next free id" from the file and
    # guards on that same id appends a second copy of the section on every re-run. P001 acquired an L25 that repeated
    # L24 word for word this way, five minutes after the L19 duplication was found by hand.
    _lf2 = pdir / "limitations.md"
    if _lf2.is_file():
        _h2 = re.findall(r"^## (L\d+) (.+)$", _lf2.read_text(encoding="utf-8", errors="replace"), re.M)
        _seen2 = {}
        for _id, _title in _h2:
            _t = re.sub(r"\s*\(?EXP-\d+\)?\s*$", "", _title).strip()
            if _t in _seen2:
                weak.append(f"limitations.md: section {_id} repeats the heading of {_seen2[_t]} ({_t[:48]!r})")
            else:
                _seen2[_t] = _id

    # Empty interpolation. The signature is a sentence that ends in ":" and is followed by a line holding nothing but
    # punctuation (the f-string's `{value}.` with `value` empty), or by end of file. P003's paper.md printed
    # "Concept-wise recoverability (of 8):" followed by a bare "." in every build from its creation until this check
    # existed; a colon line followed by a bullet list is normal prose and is not flagged.
    for _md in ("paper.md", "appendix.md", "limitations.md", "final_audit.md", "reviewer_attack.md"):
        _f = pdir / _md
        if not _f.is_file():
            continue
        _L = _f.read_text(encoding="utf-8", errors="replace").splitlines()
        for _i, _ln in enumerate(_L):
            if not _ln.rstrip().endswith(":") or not _ln.strip():
                continue
            _rest = [x.strip() for x in _L[_i + 1:] if x.strip()]
            if not _rest:
                weak.append(f"{_md}: line {_i + 1} ends in ':' and the file ends there "
                            f"({_ln.strip()[:60]!r})")
            elif re.fullmatch(r"[.。,;:]+", _rest[0]):
                weak.append(f"{_md}: line {_i + 1} ends in ':' and the next content is a bare "
                            f"{_rest[0]!r} - an interpolated value came out empty ({_ln.strip()[:60]!r})")
    # Collision levels must carry the means to re-derive them. P001's matrix shipped levels the frozen rule reproduced
    # on 2 of 19 rows (EXP-0097), and nothing detected it, because the column was written before the rule existed and
    # never re-derived. A row with a level and no re-derived counterpart is now a weakness, not a silent citation.
    lm = pdir / "literature_matrix.csv"
    if lm.is_file():
        _lr = [r for r in csv.DictReader(io.StringIO(lm.read_text(encoding="utf-8", errors="replace")))]
        _no_prov = [r.get("cite_key", "?") for r in _lr
                    if re.match(r"^L[0-4]\b", str(r.get("overlap_level") or ""))
                    and not str(r.get("overlap_level_rule_rederived") or r.get("level_rederived_by") or "").strip()]
        if _no_prov:
            weak.append(f"literature_matrix.csv: {len(_no_prov)} row(s) carry a level with no re-derived "
                        f"counterpart: {', '.join(_no_prov[:6])}")

    # A count asserted in the audit record must equal the count in the file it describes
    fa2 = pdir / "final_audit.md"
    if fa2.is_file() and cf.is_file():
        _n = max(0, len([r for r in csv.reader(io.StringIO(cf.read_text(encoding="utf-8", errors="replace")))
                         if r]) - 1)
        for _m in re.finditer(r"\| (\d+) claims", fa2.read_text(encoding="utf-8", errors="replace")):
            if int(_m.group(1)) != _n:
                weak.append(f"final_audit.md says {_m.group(1)} claims, the matrix has {_n}")
    _dvp = pdir / "deviations.md"
    if fa2.is_file() and _dvp.is_file():
        # Counted as the generator counts them: one deviation per table row. The old pattern was `^\| D\d+ \|`, which
        # matched wave-1 ids only, so a wave whose ids are `W5-D01` was read as having 6 deviations while its file
        # carried 15 - the check reported a content mismatch that was its own counter failing.
        _dv_lines = [r for r in _dvp.read_text(encoding="utf-8", errors="replace").splitlines()
                     if r.startswith("|")]
        _nd = max(0, len([r for r in _dv_lines if set(r) - set("|-: ")]) - 1)
        for _m in re.finditer(r"Deviations \|\s*(\d+) recorded",
                              fa2.read_text(encoding="utf-8", errors="replace")):
            if int(_m.group(1)) != _nd:
                weak.append(f"final_audit.md says {_m.group(1)} deviations recorded, {_dvp.name} has {_nd}")

    # The entry script must find an interpreter on its own: a frozen absolute default is only reproducible on the
    # machine that wrote it. The probe has to test candidates by executing them, because the `python` a reviewer's
    # PATH resolves to on Windows is often the Store stub, which exits 49 without importing anything.
    rs = pdir / "reproduce.sh"
    if rs.is_file():
        _rt = rs.read_text(encoding="utf-8", errors="replace")
        if "py_ok(" not in _rt:
            weak.append("reproduce.sh pins one absolute interpreter path instead of probing candidates by running "
                        "them, so it is not reproducible off the machine that wrote it")
        elif '-c "import sys"' not in _rt or "AIB_PYTHON" not in _rt:
            weak.append("reproduce.sh has a py_ok probe that does not test candidates by executing them, or ignores "
                        "AIB_PYTHON")

    # A `verify_status` that names a person's future action is an unmet step living in a shipped artefact. EXP-0111
    # cleared the four rows that said so; this keeps them cleared, and only looks at that column, because every
    # rule-graded row legitimately says "(rule grade, unverified)" in `overlap_level`.
    lm2 = pdir / "literature_matrix.csv"
    if lm2.is_file():
        _lr2 = [r for r in csv.DictReader(io.StringIO(lm2.read_text(encoding="utf-8", errors="replace")))]
        _pend = [r.get("cite_key", "?") for r in _lr2
                 if re.search(r"pending_hand_check|\bUNVERIFIED\b", str(r.get("verify_status") or ""))]
        if _pend:
            weak.append(f"literature_matrix.csv: {len(_pend)} row(s) still owe a human check "
                        f"({_pend[0][:38]}{';' if len(_pend) > 1 else ''}) - recover the abstract or label the row "
                        f"terminal with the channels tried (EXP-0111)")

    # §0 defines `figures/` as 论文全部图 and §15 asks each paper to plan its figures and tables, so an artefact that
    # appears nowhere in the manuscript is a stockpile rather than a paper figure, and a package with no plan file has
    # an unmapped §15. Both were true of every package before `embed_paper_artefacts.py` existed.
    plan = pdir / "FIGURE_PLAN.md"
    if not plan.is_file():
        weak.append("no FIGURE_PLAN.md, so spec §15's roles are not mapped onto the shipped artefacts")
    paper = pdir / "paper.md"
    if paper.is_file():
        _pp = paper.read_text(encoding="utf-8", errors="replace")
        _un = [f.name for f in sorted((pdir / "figures").glob("*.pdf")) if f.name not in _pp]
        _ut = [f.name for f in sorted((pdir / "tables").glob("*.csv")) if f.name not in _pp]
        if _un or _ut:
            weak.append(f"{len(_un)} figure(s) and {len(_ut)} table(s) shipped but named nowhere in paper.md "
                        f"({(_un or _ut)[0]}) - §0 items 10-11 make them part of the paper")

    # `reproduce.sh` is itself a generated file in three packages, and a builder that drops a step silently un-wires the
    # §15 plan and the manuscript placement. Checked here so the loss shows up as an audit line, not only as an
    # orphaned FIGURE_PLAN.md after a full rebuild round.
    rs2 = pdir / "reproduce.sh"
    if rs2.is_file():
        _rt2 = rs2.read_text(encoding="utf-8", errors="replace")
        _miss_steps = [s for s in ("export_figure_plan.py", "embed_paper_artefacts.py") if s not in _rt2]
        if _miss_steps:
            weak.append(f"reproduce.sh no longer declares {_miss_steps} - its generator dropped a §15 step")

    # A shipped sentence that says work is owed is a human step living in a delivered artefact. Sentences that close an
    # owed item, describe the reporting convention, or quote an earlier state are not flagged - the negation cues below
    # are what distinguishes "this is owed" from "this was owed and is now measured".
    _owed, _neg = [], ("not owed", "never owed", "nothing owed", "instead of", "used to", "is written as",
                       "carried that", "no human step", "all executed", "were owed", "had carried")
    for _md in sorted(pdir.glob("*.md")):
        for _s in re.split(r"(?<=[。.!])\s+", _md.read_text(encoding="utf-8", errors="replace")):
            low = _s.lower()
            if any(k in low for k in ("still owed", "remains owed", "owed to a person", "owed by a human",
                                      "still needs a human", "awaiting a human")) and not any(n in low for n in _neg):
                _owed.append(f"{_md.name}: {re.sub(chr(92) + 's+', ' ', _s.strip())[:90]}")
    if _owed:
        weak.append(f"{len(_owed)} sentence(s) in shipped documents read as work a person still owes "
                    f"({_owed[0]}) - close it by measurement or state the measured boundary instead")

    # Two provenance checks that only exist because P004 turned out to hold copies of P001's, P003's and P005's
    # processed tables (moved to `docs/archived/stray_processed_in_P004/`), and one of its figure captions cited a path
    # that belonged to another paper. §0 item 9 makes `results_processed/` this package's own generated summaries, and a
    # citation is only evidence if the file it names exists where it says it does.
    #
    # Round 2 widened what a package may legitimately hold: a package that cites a shared run - the programme's
    # contamination and cost censuses, another paper's second auditor, a wave premise census - has to be able to open
    # it, so `mirror_evidence` copies those artefacts in. The defect this rule must still catch is the older one: a
    # run belonging to one other package, present here although nothing in this package ever names it.
    _reg_own, _regf = {}, PROGRAM / "experiment_registry.csv"
    if _regf.is_file():
        for _r in csv.DictReader(io.StringIO(_regf.read_text(encoding="utf-8", errors="replace"))):
            _eid = (_r.get("exp_id") or "").replace("-", "")
            _reg_own.setdefault(_eid, set()).update(
                x for x in re.split(r"[;,\s]+", _r.get("paper_id") or "") if re.fullmatch(r"P[0-9]{3}|programme", x))
    _said = set()
    # the same documents the packaging rule reads when it decides what a citation obliges the package to hold -
    # including the dated records under results_raw/, which are the estate's own day-of-run readings and name runs
    # no other file in the package mentions. Reading a narrower set here made a legitimately cited record read as
    # a foreign object, and the two rules contradicted each other.
    for _f in list(pdir.glob("*.md")) + list(pdir.glob("*.csv")) + list((pdir / "tables").glob("*.csv")) \
            + list((pdir / "scripts").glob("*.py")) + list((pdir / "results_raw").glob("*.md")):
        if _f.is_file():
            _said |= set(re.findall(r"EXP-?(0\d{3})", _f.read_text(encoding="utf-8", errors="replace")))
    _stray = []
    for _sub, _pat in (("results_processed", "EXP*.csv"), ("results_raw", "EXP*.json")):
        for _f in sorted((pdir / _sub).glob(_pat)):
            _o = _reg_own.get(_f.name[:7], set())
            _here = pdir.name[:4]
            if not _o or _here in _o or "programme" in _o or _f.name[3:7] in _said:
                continue
            _stray.append(f"{_sub}/{_f.name} (registry attributes EXP-{_f.name[3:7]} to "
                          f"{'/'.join(sorted(_o))}, and nothing in this package names that run)")
    if _stray:
        weak.append(f"{len(_stray)} file(s) in this package's evidence folders belong to another paper's experiment "
                    f"({_stray[0]}) - §0 item 9 reserves them for this package's own summaries")
    _dangling = []
    for _doc in sorted(list(pdir.glob("*.md")) + [pdir / "tables" / "README.md"]):
        if not _doc.is_file():
            continue
        for _rel in sorted(set(re.findall(
                r"(?:results_processed|tables|figures|results_raw|configs|scripts)/[\w.\-]+"
                r"\.(?:csv|json|pdf|svg|py|txt|jsonl)",
                _doc.read_text(encoding="utf-8", errors="replace")))):
            if "*" in _rel or "?" in _rel:                   # a wildcard citation names a family, not a file
                continue
            if not (pdir / _rel).is_file():
                _dangling.append(f"{_doc.name}: {_rel}")
    if _dangling:
        weak.append(f"{len(_dangling)} path(s) cited by this package's documents do not resolve inside it "
                    f"({_dangling[0]}) - cite the owning package's full path instead")

    out["missing"] = missing
    # an OPEN row in the package's own coverage statement is an unrun experiment: "missing=none" must not be allowed
    # to stand next to it
    _ec = pdir / "E_COVERAGE.md"
    if _ec.is_file():
        _t = _ec.read_text(encoding="utf-8", errors="replace")
        _m = re.search(r"\*\*(\d+) step\(s\) are OPEN\*\*", _t)
        if _m and int(_m.group(1)):
            _open = [ln.split("|")[1].strip() for ln in _t.splitlines()
                     if re.match(r"^\| E\d\d \|.*\| OPEN \|", ln)]
            weak.append(f"E_COVERAGE.md: {_m.group(1)} step(s) of the spec's minimum package are OPEN "
                        f"({', '.join(_open) or 'the count line says so but no row matched'})")
    # the E19/E13 record has to be a CLAIM, not only a document: a package builder that regenerates
    # claims_evidence_matrix.csv wholesale silently drops the rows the recorders add, and the paper would then cite an
    # audit no reader could find in the matrix.
    _cm = pdir / "claims_evidence_matrix.csv"
    if _cm.is_file():
        _t = _cm.read_text(encoding="utf-8", errors="replace")
        _cited = set(re.findall(r"EXP-\d{4}", _t))
        _need = {"EXP-0104", "EXP-0105"}
        if not (_need & _cited):
            weak.append("claims matrix cites neither EXP-0104 (E19 contamination) nor EXP-0105 (E13 cost) - the "
                        "package's own builders rewrote the matrix and the recorders' rows are gone")
    out["weak"] = weak
    out["ready_for_submission_gate"] = (not missing) and (not weak)
    return out


def registry_state() -> dict:
    # ragged-row check: a recorder that appends by position under a wider header shifts every later column, and the
    # paper_id vocabulary test cannot see it because it only reads one column
    _raw = [r for r in csv.reader(io.StringIO((PROGRAM / "experiment_registry.csv").read_text(encoding="utf-8"))) if r]
    _ragged = [r[0] for r in _raw[1:] if len(r) != len(_raw[0])]
    if _ragged:
        raise SystemExit(f"registry has {len(_ragged)} ragged row(s): {_ragged[:6]}")
    reg = pd.read_csv(PROGRAM / "experiment_registry.csv")
    topics = pd.read_csv(PROGRAM / "topic_registry.csv")
    out = {"experiments": int(len(reg)),
           "registry_paper_id_vocabulary": registry_paper_id_vocabulary(PROGRAM),
           "experiments_by_status": reg.status.value_counts().to_dict(),
           "topics_total": int(len(topics)),
           "topics_by_stage": topics.status.value_counts().to_dict(),
           "topics_past_w0": int((topics.status != "w0_audit").sum())}
    led = ROOT / "papers/P001_routing_failure_qpp/test_eval_ledger.json"
    if led.is_file():
        out["P001_test_evaluations"] = len(json.loads(led.read_text(encoding="utf-8"))["evaluations"])
    # The handoff document was hand-maintained for three sessions and was wrong every time (it said "37 experiments"
    # when the registry held 103). It is generated now, so a stale one is a bug rather than a fact of life.
    ps = PROGRAM / "PROGRAM_STATUS.md"
    if ps.is_file() and "finished_at" in reg.columns:
        m = re.search(r"Generated (\d{4}-\d{2}-\d{2} \d{2}:\d{2})", ps.read_text(encoding="utf-8", errors="replace"))
        newest = str(pd.to_datetime(reg["finished_at"], errors="coerce").max())
        gen = pd.to_datetime(m.group(1)) if m else pd.NaT
        out["program_status"] = {"generated_at": (str(gen) if pd.notna(gen) else "no Generated line"),
                                 "newest_experiment_finished": newest,
                                 "stale": bool(pd.notna(gen) and pd.notna(pd.to_datetime(newest, errors="coerce"))
                                               and gen < pd.to_datetime(newest))}
    return out


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    papers = sorted(p for p in (ROOT / "papers").iterdir() if p.is_dir() and p.name.startswith("P"))
    rows = [audit_paper(p) for p in papers]
    state = registry_state()
    pd.DataFrame([{"paper": r["paper"], "missing": "; ".join(r["missing"]), "weak": "; ".join(r["weak"]),
                   "gate_ready": r["ready_for_submission_gate"]} for r in rows]).to_csv(
        PROGRAM / "package_audit.csv", index=False)
    summary = {"generated_at": time.strftime("%Y-%m-%dT%H:%M:%S"), "papers": rows, "program": state}
    (PROGRAM / "package_audit.json").write_text(json.dumps(summary, indent=1, ensure_ascii=False), encoding="utf-8")
    for r in rows:
        _w = r["weak"]
        _shown = ("none" if not _w else str(_w[:4]) + (f" (+{len(_w) - 4} more)" if len(_w) > 4 else ""))
        print(f"{r['paper']}{' [BLOCKED]' if r.get('blocked') else ''}: "
              f"missing={r['missing'] or 'none'} weak={_shown}"
              + (f"  ({r['note']})" if r.get("note") else ""))
    v = state["registry_paper_id_vocabulary"]
    print(json.dumps({k: state[k] for k in ("experiments", "registry_paper_id_vocabulary", "topics_total")},
                     ensure_ascii=False)[:400])
    if v["violations"]:
        print(f"[audit] REGISTRY paper_id VOCABULARY VIOLATIONS ({len(v['violations'])}): {v['violations'][:10]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
