"""EXP-0092 recorder: the AgentTrove instrument, its measured ceiling, and what it changes in P002's record.

P002's `final_audit.md` carried two blockers: the frozen RQ4 step (settled by EXP-0087, which the instrument failed)
and "a second corpus the codex can actually reach", which until now was an assumption - AgentTrove was 90.1%
uncodable, and nobody had established whether that is a property of the corpus or of the parser. EXP-0092 measures
it by coding the same turns three ways with a second instrument frozen in `protocol_freeze_agenttrove.md`.

The recorder writes the section, one deviation and one registry row. The paper text, claim K8, the reviewer row and
the gate decision are generated by `build_package.py` from the same artefact, so a rebuild cannot restore the older,
weaker wording.

    python record_exp0092_p002.py
"""
from __future__ import annotations

import csv, io, json, pathlib, re, sys, time

ROOT = next(a for a in [pathlib.Path(__file__).resolve().parent, *pathlib.Path(__file__).resolve().parents]
            if (a / "00_program_registry").is_dir())
P = ROOT / "papers" / "P002_isp_stage_measurement"
NOW = time.strftime("%Y-%m-%dT%H:%M:%S")


def line(r):
    b = io.StringIO(); csv.writer(b, lineterminator="\r\n").writerows([r]); return b.getvalue()


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    f = sorted((ROOT / "results_raw").glob("EXP0092_agenttrove_codex_*.json"))[-1]
    d = json.loads(f.read_text(encoding="utf-8"))
    A0 = d["arms"]["arm0_frozen_extractor_frozen_cues"]
    A1 = d["arms"]["arm1_new_extractor_frozen_cues"]
    A2 = d["arms"]["arm2_new_extractor_agenttrove_cues"]
    L = d["ladder"]
    if not L:
        raise SystemExit("ABORT: EXP-0092 produced no ladder - the AgentTrove arms were never comparable")
    if not d["exp0031_reference"]["arm0_reproduces"]:
        raise SystemExit("ABORT: arm0 does not reproduce EXP-0031, so the decomposition is not a parser comparison")
    # Round 2: the per-trajectory column used to be `round(mean, 4) * round(turns / trajectories, 2)` - a product of
    # two roundings whose second factor exists nowhere in the record. The ladder now measures the product itself, so
    # that is what is printed; the unrounded ratio stays only as the multiplier the table names, and the old
    # arithmetic remains as the fallback for a record written before the field existed.
    tpt_raw = A2["shares"]["turns"] / max(1, L["trajectories"])
    tpt = L.get("turns_per_trajectory") or round(tpt_raw, 6)

    def traj(entry):
        m = entry.get("mean_bits_per_trajectory")
        return round(m, 3) if isinstance(m, (int, float)) else round(entry["mean"] * tpt_raw, 3)

    g = L["gains_first_minus"]
    doc = f"""# The second corpus, measured: a frozen AgentTrove codex and the ceiling it reaches (EXP-0092)

Artefact `{f.name}`; instrument frozen in `protocol_freeze_agenttrove.md`; code
`02_shared_code/behavior_tagger/isp_stage_codex_agenttrove.py`; seed {d['seed']}; {d['wallclock_sec']}s.
Sample: {d['sample']['shards_read']} shards, {d['sample']['trajectories']:,} trajectories,
{d['sample']['assistant_turns']:,} assistant turns - the identical AgentTrove sample EXP-0031 used, and arm0
reproduces EXP-0031's uncodable share to the digit ({A0['shares']['uncodable']}), which is what makes the other two
arms a parser comparison rather than a resample.

## What the freeze fixed, and how it is checked

The addendum's `trove-cues` block is the machine-checked form of the instrument: the script parses it and refuses to
run if any printed regex differs from the one in the code. A freeze that nothing reads is a comment; this one is a
precondition. Construct definitions, the eight stage labels, the priority order, the 0.80 / 0.20 / 0.80 RQ1
conjuncts, the RQ2 three-conjunct criterion and the 5.0 / 2.0 bit floors are all inherited from
`protocol_freeze.md` unchanged - including the floors, which were set for 15-step capped trajectories and are
applied here as they stand.

## The decomposition

| arm | extractor | cue table | codable | uncodable | largest stage | RQ1 all three |
|---|---|---|---|---|---|---|
| 0 | fenced ```bash (frozen) | frozen | {A0['shares']['codable']} | {A0['shares']['uncodable']} | {A0['shares']['largest_share']} | {A0['rq1']['passes_all_three']} |
| 1 | `keystrokes`/`analysis` payload | frozen | {A1['shares']['codable']} | {A1['shares']['uncodable']} | {A1['shares']['largest_share']} | {A1['rq1']['passes_all_three']} |
| 2 | payload | AgentTrove cues (frozen) | **{A2['shares']['codable']}** | {A2['shares']['uncodable']} | {A2['shares']['largest_share']} | **{A2['rq1']['passes_all_three']}** |

Reading the payload buys {round(A1['shares']['codable'] - A0['shares']['codable'], 4)}; the corpus-specific cue
vocabulary buys a further {round(A2['shares']['codable'] - A1['shares']['codable'], 4)}. Supporting facts from the
same pass: {d['sample']['keystrokes_share']:.1%} of assistant turns carry a `keystrokes` payload and only
{d['sample']['valid_json_share']:.1%} parse as valid JSON, so the gain comes from not requiring a whole-turn JSON
object, which is the assumption that made this corpus look unmeasurable.

Stage distribution under arm 2: {json.dumps(A2['shares']['stage_shares'], ensure_ascii=False)}.

## The ladder on the now-codable turns

{L['trajectories']:,} trajectories, {L['turns']:,} turns, {tpt} turns per trajectory; split by instance
({L['instances_dev']} dev, {L['instances_report']} report), {L['bootstraps']} instance-clustered draws:

| contrast | bits/turn | bits/trajectory (x {tpt}) | 95% CI (instances) |
|---|---|---|---|
| B2 - B1 (marginal) | {g['zero_order']['mean']} | {traj(g['zero_order'])} | {g['zero_order']['ci95_instances']} |
| B2 - B4 (position only) | {g['position_only']['mean']} | {traj(g['position_only'])} | {g['position_only']['ci95_instances']} |
| B2 - B3 (previous command) | {g['previous_command']['mean']} | {traj(g['previous_command'])} | {g['previous_command']['ci95_instances']} |

Against the frozen criterion: the CI condition on B2-B4 {"excludes" if g['position_only']['ci95_instances'][0] > 0
else "does not exclude"} zero ({g['position_only']['ci95_instances']}), and both magnitude conditions fail by more
than an order of magnitude ({traj(g['zero_order'])} of 5.0, {traj(g['position_only'])} of 2.0 bits
per trajectory). B3 again outranks B2, as it did in SWE-ZERO, which is the one pattern the two corpora share.

## What this changes, and what it does not

1. **The claim "the instrument is corpus-bound" is now decomposed.** Most of the loss is a container-format
   assumption in the parser, not an absence of stage structure - which is the more interesting statement and the one
   the paper can now make (K8, section 4).
2. **The second-corpus replication stays untested**, because arm 2 misses the 0.80 conjunct by
   {round(0.80 - A2['shares']['codable'], 4)} and the held-out set is {L['instances_report']} instances. The gate
   decision says that as a measurement instead of as an expectation.
3. **No threshold moved.** The failure is 0.7634 against 0.80 and it is recorded as a failure; the floors set for
   capped trajectories are applied unchanged, and the resulting magnitude gap is reported as a limit of the
   criterion across corpora rather than a reason to re-cut it.
4. **The instrument is still new.** A replication performed with an instrument built for the purpose is weaker
   evidence than one performed with the frozen one, and nothing here claims otherwise; the addendum records that the
   cue table was written before the run, and the drift check is what makes that checkable.
5. **Not yet done for this codex:** the rubric-invariance test EXP-0087 imposed on the frozen codex. The addendum
   commits to it (section C5), so it is owed before this instrument can carry a distribution claim of its own.
"""
    # Addendum C5's owed rubric-invariance test has since been run. The wording below is substituted only when the
    # EXP-0112 artefact exists, so a checkout without that run still regenerates the honest "not yet done" statement
    # rather than a number nothing measured.
    e112 = sorted((ROOT / "results_raw").glob("EXP0112_agenttrove_rubric_invariance_*.json"))
    if e112:
        j112 = json.loads(pathlib.Path(e112[-1]).read_text(encoding="utf-8"))
        ci112 = j112["kappa_clustered_ci95"]
        done112 = (f"5. **Rubric invariance measured, and the instrument failed it (EXP-0112).** The test addendum C5 "
                   f"committed to was run against a second, independently written AgentTrove codex on the same "
                   f"{j112['sample']['turns_compared']:,} turns: Cohen kappa {j112['kappa']} (95% CI "
                   f"{ci112[0]}-{ci112[1]}) against the pre-declared bar {j112['kappa_bar']} -> "
                   f"`{j112['verdict']}`. The stage distribution is therefore reported as instrument-dependent and "
                   f"carries no distribution claim of its own; see `agenttrove_rubric_invariance_exp0112.md`.")
        doc = re.sub(r"5\. \*\*Not yet done for this codex:\*\*.*", done112, doc, flags=re.S)

    (P / "agenttrove_instrument_exp0092.md").write_text(doc, encoding="utf-8", newline="")
    bad = re.findall(r"\|\s*\?\s*\||\bNone\b", doc)
    if bad:
        raise SystemExit(f"ABORT: generated document carries a placeholder: {bad[:5]}")
    print(f"  wrote agenttrove_instrument_exp0092.md ({len(doc.split())} words)")

    dv = P / "deviations.md"
    t = dv.read_text(encoding="utf-8")
    if "EXP-0092" not in t:
        used = {int(x) for x in re.findall(r"^\| D(\d+) \|", t, re.M)}
        for g in (ROOT / "papers").glob("*/deviations.md"):
            if g != dv:
                used |= {int(x) for x in re.findall(r"^\| D(\d+) \|", g.read_text(encoding="utf-8"), re.M)}
        did = max(used | {0}) + 1
        t = t.rstrip() + "\n" + (
            f"| D{did} | {NOW} | 为 AgentTrove 新写并冻结一套 codex（EXP-0092，`protocol_freeze_agenttrove.md`），"
            "并把冻结的 cue 表做成脚本启动时逐条校验的机器可读块 | 第二语料 90.1% uncodable 究竟是语料性质还是解析器"
            f"假设，此前只是假设。三臂对照：解析 payload 使 codable {A0['shares']['codable']}->{A1['shares']['codable']}，"
            f"再加语料词表到 {A2['shares']['codable']}，仍低于 0.80 判据 | 否（0.80/0.20/0.80 与 5.0/2.0 门槛一律沿用，"
            "未因结果调整） | 后果：blocker(b) 从假设改为测得（K8、§4、final_audit gate、topic T008 阻断项），"
            "第二语料复现仍未达成；该新仪器的 rubric 不变性检验按 addendum C5 仍为欠项 |\n")
        dv.write_text(t, encoding="utf-8", newline="")
        print(f"  deviations: appended D{did}")

    rp = ROOT / "00_program_registry" / "experiment_registry.csv"
    rows = [r for r in csv.reader(io.StringIO(rp.read_text(encoding="utf-8"))) if r]
    hdr, body = rows[0], rows[1:]
    if "EXP-0092" not in {r[0] for r in body}:
        rec = dict.fromkeys(hdr, "")
        rec.update({
            "exp_id": "EXP-0092", "paper_id": "P002", "topic_id": "T008",
            "stage": "rq1_second_corpus_instrument",
            "script": "02_shared_code/behavior_tagger/isp_stage_codex_agenttrove.py",
            "config": f"three arms over EXP-0031's identical AgentTrove sample ({d['sample']['shards_read']} shards x "
                      f"1500 rows, seed {d['seed']}): arm0 frozen extractor+frozen cues, arm1 payload extractor+"
                      f"frozen cues, arm2 payload extractor+AgentTrove cues frozen in protocol_freeze_agenttrove.md; "
                      "the frozen `trove-cues` block is verified regex-by-regex against the code before any data is "
                      "read; RQ1 conjuncts, RQ2 criterion and the 5.0/2.0 floors inherited unchanged",
            "seed": str(d["seed"]), "started_at": d["started_at"], "finished_at": NOW,
            "status": f"CEILING {A2['shares']['codable']} < 0.80: codable {A0['shares']['codable']} -> "
                      f"{A1['shares']['codable']} (payload) -> {A2['shares']['codable']} (cues); replication still "
                      "untestable",
            "outputs": f"results_raw/{f.name}; papers/P002_isp_stage_measurement/agenttrove_instrument_exp0092.md; "
                       "papers/P002_isp_stage_measurement/protocol_freeze_agenttrove.md",
            "notes": "arm0 reproduces EXP-0031 exactly, so the arms differ only in instrument; "
                     f"{d['sample']['keystrokes_share']:.1%} of turns carry keystrokes while "
                     f"{d['sample']['valid_json_share']:.1%} parse as JSON, which is where the 0.656 comes from; "
                     "ladder on arm2 reported with the frozen criterion applied unchanged",
            "enters_paper": "yes - claim K8, section 4, final_audit gate decision (b), reviewer attack 13, "
                            "deviations, topic_registry blocking issue"})
        body.append([rec[x] for x in hdr])
        rp.write_text("".join(line(x) for x in [hdr] + body), encoding="utf-8", newline="")
        print("  registry: EXP-0092 added")
    chk = [r for r in csv.reader(io.StringIO(rp.read_text(encoding="utf-8"))) if r]
    print(f"  registry rows={len(chk) - 1} ragged={sum(1 for r in chk[1:] if len(r) != len(chk[0]))}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
