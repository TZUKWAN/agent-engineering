"""EXP-0112 recorder: the AgentTrove instrument's rubric-invariance result, written into P002 as measured.

Addendum C5 owed this test to the second-corpus instrument and P002 shipped for a day with item 5 of
`agenttrove_instrument_exp0092.md` reading "not yet done". The test is now run
(`02_shared_code/behavior_tagger/isp_stage_codex_agenttrove_second.py`), and the pre-declared bar was kappa >= 0.75.

The result is unfavourable and is recorded as such: the two independently realised cue tables agree only
moderately, so the AgentTrove stage distribution stays instrument-dependent and cannot carry a distribution claim of
its own - which is the outcome C5 itself specified for a kappa below the bar. Nothing here re-cuts a threshold, a cue
table or the sample; the disagreement structure is published because it is the informative part.

    python 02_shared_code/registry/record_exp0112_p002.py [--check]
"""
from __future__ import annotations

import csv, glob, io, json, pathlib, re, sys, time

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import record_exp0103_0105_docs as BASE                      # noqa: E402  add_claim/add_deviation/add_limitation/span
ROOT = BASE.ROOT
P = ROOT / "papers" / "P002_isp_stage_measurement"
DOC = "agenttrove_rubric_invariance_exp0112.md"


def latest_raw():
    f = sorted(glob.glob(str(ROOT / "results_raw" / "EXP0112_agenttrove_rubric_invariance_*.json")))
    if not f:
        raise SystemExit("ABORT: no EXP-0112 artefact on disk - run isp_stage_codex_agenttrove_second.py first "
                         "(the recorder does not re-run the measurement, and never invents one)")
    return pathlib.Path(f[-1])


def deviation_id() -> int:
    """The id this recorder already owns, or the next free one.

    Allocating max+1 on every run would hand `add_deviation` a fresh key each rebuild and append a second identical
    row, which is the growth defect this whole round has been hunting; the row is therefore claimed by the EXP-0112
    marker inside it, the same way `add_claim` keys a claim on its own experiment set.
    """
    t = (P / "deviations.md").read_text(encoding="utf-8", errors="replace")
    own = [m.group(1) for m in re.finditer(r"(?m)^\| D(\d+) \|.*EXP-0112.*$", t)]
    if own:
        return int(own[0])
    ids = [int(x) for x in re.findall(r"(?m)^\| D(\d+) \|", t)]
    return max(ids) + 1 if ids else 1


def body(j: dict) -> str:
    s, rq = j["sample"], j["rq1_under_each_table"]
    moved = ", ".join(f"`{k}` {v:+.2f} pp" for k, v in list(j["share_moves_pp"].items())[:8])
    conf = "\n".join(f"| `{k}` | {v:,} |" for k, v in j["confusion_top"].items())
    fa, fb = rq["frozen"], rq["second"]
    ci = j["kappa_clustered_ci95"]
    dw = j["bootstrap_draws_with_a_value"]
    return f"""# Rubric invariance of the AgentTrove instrument (EXP-0112)

Generated by `02_shared_code/registry/record_exp0112_p002.py` from `{j['exp_id']}` raw output
`{latest_raw().name}`. Run at {j['at']} ({j['wallclock_sec']} s). Every number below is read from that file.

## What was owed

`protocol_freeze_agenttrove.md` section C5 fixed, before any number was seen: the new instrument is "subjected to the
same rubric-invariance test EXP-0087 imposed on the frozen one (an independently written second AgentTrove codex, bar
kappa >= 0.75). A new instrument is not exempt from the test that P002's own codex failed."

## What was held constant and what was varied

{j['held_constant']}. The second cue table is a separate file
(`02_shared_code/behavior_tagger/isp_stage_codex_agenttrove_second.py`), written from the construct definitions in
`protocol_freeze.md` section 2 rather than by perturbing the frozen regexes. {j['claim_not_made']}.

## Result on the frozen sample

| quantity | value |
|---|---|
| assistant turns compared | {s['turns_compared']:,} of {s['assistant_turns_scanned']:,} scanned |
| trajectories (the cluster unit) | {s['trajectories']:,} over {s['shards']} shards, seed {s['seed']} |
| Cohen kappa (turn level) | **{j['kappa']}** |
| instance-clustered 95% interval | {ci[0]} to {ci[1]} ({dw:,} draws) |
| percent agreement | {j['percent_agreement']} |
| pre-declared bar (addendum C5) | kappa >= {j['kappa_bar']} |
| verdict | **{j['verdict']}** |

Share moves between the two tables: {moved}.

### Where the two tables disagree

| coder A -> coder B | turns |
|---|---|
{conf}

### RQ1 codability under each table

| table | codable | uncodable | largest stage | passes the frozen RQ1 conjuncts |
|---|---|---|---|---|
| instrument of EXP-0092 | {fa['codable']} | {fa['uncodable']} | {fa['largest_stage_share']} | {'yes' if fa['passes_riq1'] else 'no'} |
| second instrument | {fb['codable']} | {fb['uncodable']} | {fb['largest_stage_share']} | {'yes' if fb['passes_riq1'] else 'no'} |

## What this changes, and what it does not

* The AgentTrove stage distribution is reported as **instrument-dependent**: {j['kappa']} is below the bar C5 set, so
  no distribution claim of its own rests on it. This narrows nothing that was claimed before - EXP-0092 had already
  recorded the second-corpus replication as untested (D52) - and it removes the last outstanding item of
  `agenttrove_instrument_exp0092.md`.
* No threshold, cue table or sample was re-cut after seeing the number. {j['rule']}.
* The disagreement is concentrated, not diffuse: the top boundary alone accounts for most of it, which is the same
  shape EXP-0087 found for the frozen codex (kappa {j['kappa']} here against 0.502 there).

Raw line counts, both marginals and the full confusion structure are in the artefact named above.
"""


def main() -> int:
    check = "--check" in sys.argv
    sys.stdout.reconfigure(encoding="utf-8")
    j = json.loads(latest_raw().read_text(encoding="utf-8"))
    txt = body(j)
    if check:
        print(f"  would write {DOC} ({len(txt)} chars); claim, deviation and limitation would follow")
        return 0
    (P / DOC).write_text(txt, encoding="utf-8", newline="")
    st, fin = BASE.span(j)
    ci = j["kappa_clustered_ci95"]
    claim = (f"the AgentTrove instrument of EXP-0092 is not rubric-invariant: two independently realised cue tables on "
             f"the same {j['sample']['turns_compared']:,} turns agree at kappa {j['kappa']} (95% CI {ci[0]}-{ci[1]}), "
             f"below the kappa >= {j['kappa_bar']} bar addendum C5 set before the run, so the second-corpus stage "
             f"distribution is reported as instrument-dependent and carries no distribution claim of its own")
    row = {"claim": claim, "claim_type": "测量工具的稳健性（第二语料仪器的 rubric 不变性）",
           "experiment_id": "EXP-0112",
           "direction": "measured and unfavourable; reported as a limit of the instrument",
           "raw_result_file": f"results_raw/{latest_raw().name}",
           "table": DOC + "; results_processed/", "figure": "-",
           "test": (f"turn-level Cohen kappa with an instance-clustered bootstrap interval "
                    f"({j['bootstrap_draws_with_a_value']} draws, seed {j['sample']['seed']})")}
    did = deviation_id()
    dtext = ("EXP-0112 补做 addendum C5 欠下的第二语料仪器 rubric 不变性检验，并关闭 D52 末句所述欠项；"
             "结果不利（kappa 低于 0.75 判据）")
    dreason = (f"预先固定的判据 kappa >= {j['kappa_bar']} 未达成：kappa={j['kappa']}（聚类 bootstrap 95% CI "
               f"{ci[0]}-{ci[1]}）")
    dpointer = f"见 `{DOC}`；`agenttrove_instrument_exp0092.md` 第 5 条随之关闭"
    lim = ("第二语料（AgentTrove）的阶段分布在两套独立实现的线索表下 kappa 低于预先固定的 0.75 判据，因此该分布只作为"
           "仪器依赖的描述量报告，不支持任何跨语料的阶段分布结论。")
    print("  wrote", DOC)
    print("  claim:", BASE.add_claim(P, "K", row, False))
    print("  deviation:", BASE.add_deviation(P, f"D{did}", dtext, False, reason=dreason, pointer=dpointer))
    print("  limitation:", BASE.add_limitation(P, "rubric 不变性", lim, False))
    _register(j, st, fin)
    BASE.refresh_final_audit_counts(P)
    return 0


def _register(j: dict, st: str, fin: str) -> None:
    p = ROOT / "00_program_registry" / "experiment_registry.csv"
    rows = list(csv.reader(io.StringIO(p.read_text(encoding="utf-8", errors="replace"))))
    hdr, body_ = rows[0], rows[1:]
    vals = {"exp_id": "EXP-0112", "paper_id": "P002",
            "stage": "e112_agenttrove_rubric_invariance_C5",
            "script": "02_shared_code/behavior_tagger/isp_stage_codex_agenttrove_second.py",
            "config": (f"kappa_bar={j['kappa_bar']} (addendum C5); draws={j['bootstrap_draws_with_a_value']}; "
                       f"seed={j['sample']['seed']}; shards={j['sample']['shards']}; "
                       f"rows_per_shard={j['sample']['rows_per_shard']}"),
            "seed": str(j["sample"]["seed"]), "started_at": st, "finished_at": fin,
            "status": f"{j['verdict']} (kappa {j['kappa']})",
            "outputs": f"results_raw/{latest_raw().name}; papers/P002_isp_stage_measurement/{DOC}",
            "notes": ("closes addendum C5's owed test on the second-corpus instrument. Two independently written cue "
                      "tables, extraction and the matching discipline imported from the published codex so only the "
                      "table differs. The bar was not met and no threshold, cue or sample was re-cut."),
            "enters_paper": "yes - limitations and the AgentTrove instrument note", "topic_id": "T008"}
    out = [vals.get(c, "") for c in hdr]
    i = next((k for k, r in enumerate(body_) if r and r[0] == "EXP-0112"), None)
    if i is None:
        body_.append(out)
    else:
        body_[i] = out
    buf = io.StringIO()
    csv.writer(buf, lineterminator="\r\n").writerows([hdr] + body_)
    p.write_text(buf.getvalue(), encoding="utf-8", newline="")
    print("  registry:", "row refreshed" if i is not None else "EXP-0112 registered")


if __name__ == "__main__":
    raise SystemExit(main())
