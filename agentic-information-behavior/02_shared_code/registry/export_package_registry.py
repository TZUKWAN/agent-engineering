"""Spec items 7 and 14 per package: the paper's own `experiment_registry.csv`, plus an index of its runs in `logs/`.

Item 7 is the register itself; item 14 asks for logs of successful **and failed** runs. The programme kept one master
registry at `00_program_registry/experiment_registry.csv` and no per-package copy, and `package_audit.py` did not notice
- the item it labelled "spec item 7" was the pilot report - so a deliverable was unverified while five packages printed
`missing=none`. This script writes the extract, and next to it `logs/RUN_INDEX.md`, which lists every run of the paper
with its status, names the failed/aborted/negative/superseded ones, and says where each log file physically is (three
packages keep a sibling's log; nothing is moved or deleted here, only reported).

The index is ordered by registry rows rather than by a set: string hashing is salted per process, and a set iteration
made the superseded-artefact table reorder between runs - the instability a generated index must not have. `--check`
reports staleness for both files without writing.

A row belongs to a package if `paper_id` names it (the column is `;`-joined after the EXP-0077/78 normalisation), or if
the package's own `claims_evidence_matrix.csv` cites its `exp_id` - the second rule is what pulls in programme-level
steps such as the clean-room replication (EXP-0079) or a second matcher, which a paper's claims do rest on.

    python 02_shared_code/registry/export_package_registry.py            # all packages
    python 02_shared_code/registry/export_package_registry.py --check    # report, write nothing

Idempotent: the extract is regenerated from the programme registry every time, so a re-run rewrites identical bytes
unless the registry itself changed.
"""
from __future__ import annotations
import argparse, csv, io, json, pathlib, re, sys, time

ROOT = next(a for a in [pathlib.Path(__file__).resolve().parent,
                        *pathlib.Path(__file__).resolve().parents] if (a / "00_program_registry").is_dir())
REG = ROOT / "00_program_registry" / "experiment_registry.csv"
SUPERSEDED = ROOT / "results_raw" / "SUPERSEDED_ARTIFACTS.json"
PAPERS = sorted(p for p in (ROOT / "papers").glob("P0*") if p.is_dir())
EXTRA = ["included_because", "exported_from", "exported_at"]
# spec item 14 asks for logs of successful *and failed* runs; these words identify the runs that are not a success
FAILED_WORDS = ("fail", "abort", "not_established", "reject", "open", "withdrawn", "untestable", "superseded",
                "no_identifiability", "blocked", "error", "defect", "negative", "below")


def log_location(exp_id: str) -> str:
    """Where a run's log physically is. Three packages keep a sibling's file, so the index reports the location rather
    than pretending each directory is complete; nothing is moved or deleted by this script."""
    hits = [q for q in sorted(ROOT.glob("papers/P00*/logs/*")) if q.is_file() and exp_id in q.name]
    if hits:
        return ", ".join(f"{q.parent.parent.name}/logs/{q.name}" for q in hits[:2])
    prog = [q.name for q in sorted(ROOT.glob("logs/*")) if exp_id in q.name]
    return ("logs/" + prog[0]) if prog else "no per-run log file (recorded in the registry row instead)"


def run_index(pkg: pathlib.Path, pid: str, picked, hdr) -> str:
    """`logs/RUN_INDEX.md`: every run of this paper, its status, and the failed ones named explicitly."""
    sup = {}
    if SUPERSEDED.is_file():
        for e in json.loads(SUPERSEDED.read_text(encoding="utf-8")).get("superseded", []):
            sup.setdefault(e.get("exp_id"), []).append(e)
    i = {c: n for n, c in enumerate(hdr)}
    failed = [r for r in picked if any(w in str(r[i["status"]]).lower() for w in FAILED_WORDS)]
    L = [f"# Run index for {pid} (spec item 14: successful and failed runs)", "",
         f"Generated by `02_shared_code/registry/export_package_registry.py` from "
         f"`00_program_registry/experiment_registry.csv`; {len(picked)} runs belong to this package "
         f"({len(failed)} of them carry a failed, aborted, negative, bounded or superseded status). Nothing here is "
         f"entered by hand, and no artefact is deleted: failed runs stay on disk and are listed.", "",
         "| run | status | started | finished | log file |", "|---|---|---|---|---|"]
    for r in picked:
        L.append(f"| {r[0]} | {str(r[i['status']])[:70]} | {r[i['started_at']]} | {r[i['finished_at']]} | "
                 f"{log_location(r[0])} |")
    L += ["", "## Failed, aborted, negative and superseded runs", ""]
    L += ([f"- **{r[0]}** - {str(r[i['status']])[:120]}" for r in failed] or
          ["None: every run recorded for this package completed with a supportive status."])
    # ordered by the registry rows, not by a set: string hashing is salted per process, so a set iteration made this
    # table come out in a different order on every run, which is exactly the instability a generated index must not have
    seen_ids, sup_rows = set(), []
    for r in picked:
        for e in sup.get(r[0], []):
            if e["file"] in seen_ids:
                continue
            seen_ids.add(e["file"])
            sup_rows.append((e["file"], re.sub(r"\s+", " ", str(e.get("reason", "")))))
    if sup_rows:
        L += ["", "## Superseded artefacts of this package (kept, never deleted)", "",
              "| file | why it was superseded |", "|---|---|"]
        L += [f"| `{f}` | {txt[:200]} |" for f, txt in sup_rows]
    L += ["", f"Register extract: `experiment_registry.csv` in this directory ({len(picked)} rows, with the column "
              "`included_because` saying whether the row is here by `paper_id`, because this package's claims cite it, "
              "or both)."]
    return "\n".join(L) + "\n"


def cited_experiments(pkg: pathlib.Path):
    cf = pkg / "claims_evidence_matrix.csv"
    if not cf.is_file():
        return set()
    out = set()
    for r in csv.DictReader(io.StringIO(cf.read_text(encoding="utf-8"))):
        # the column sometimes carries a compound or annotated citation ("EXP-0021+EXP-0022",
        # "EXP-0035 (table16_subset_transfer.csv)"), so ids are matched rather than split on separators
        out.update(re.findall(r"EXP-\d{4}", str(r.get("experiment_id") or "")))
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="compare with what is on disk without writing")
    ap.add_argument("--paper", default="", help="restrict to one package id (e.g. P003) so a chain can refresh its own "
                                                "extract without touching the others")
    a = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")
    raw = [r for r in csv.reader(io.StringIO(REG.read_text(encoding="utf-8"))) if r]
    hdr, body = raw[0], raw[1:]
    if "paper_id" not in hdr or "exp_id" not in hdr:
        raise SystemExit(f"ABORT: the registry has no paper_id/exp_id column: {hdr}")
    pi, ei = hdr.index("paper_id"), hdr.index("exp_id")
    now = time.strftime("%Y-%m-%dT%H:%M:%S")
    written = []
    pkgs = [q for q in PAPERS if not a.paper or q.name.startswith(a.paper)]
    if not pkgs:
        raise SystemExit(f"ABORT: no package matches {a.paper!r}")
    for pkg in pkgs:
        pid = pkg.name[:4]
        cites = cited_experiments(pkg)
        picked = []
        for r in body:
            named = pid in [x.strip()[:4] for x in r[pi].replace(",", ";").split(";")]
            cited = r[ei].strip() in cites
            if not (named or cited):
                continue
            why = "paper_id" if named and not cited else "cited_by_claims" if cited and not named else "both"
            picked.append(r + [why, "00_program_registry/experiment_registry.csv", now if not a.check else ""])
        if not picked:
            raise SystemExit(f"ABORT: {pid} has no registry rows at all - the paper would ship an empty register")
        out = pkg / "experiment_registry.csv"
        buf = io.StringIO()
        w = csv.writer(buf, lineterminator="\r\n")
        w.writerow(hdr + EXTRA)
        w.writerows(picked)
        text = buf.getvalue()
        if a.check:
            # `exported_at` legitimately differs on every run, so the comparison ignores that last column
            same = (out.is_file() and
                    [r[:-1] for r in csv.reader(io.StringIO(out.read_text(encoding="utf-8"))) if r] ==
                    [r[:-1] for r in csv.reader(io.StringIO(text)) if r])
            idx = pkg / "logs" / "RUN_INDEX.md"
            idx_ok = idx.is_file() and idx.read_text(encoding="utf-8") == run_index(pkg, pid, picked, hdr)
            print(f"  {pid}: {len(picked)} rows -> {out.name} "
                  f"{'+'.join([] if same else ['STALE']) or 'up to date'} register, "
                  f"{'index ok' if idx_ok else 'index absent or stale'}")
            if not same:
                written.append(pid)
            continue
        out.write_text(text, encoding="utf-8", newline="")
        (pkg / "logs").mkdir(exist_ok=True)
        idx = (pkg / "logs" / "RUN_INDEX.md")
        idx.write_text(run_index(pkg, pid, picked, hdr), encoding="utf-8", newline="")
        print(f"  {pid}: wrote {out.name} with {len(picked)} rows "
              f"({sum(1 for p in picked if p[-3] == 'paper_id')} by paper_id, "
              f"{sum(1 for p in picked if p[-3] == 'cited_by_claims')} cited by claims, "
              f"{sum(1 for p in picked if p[-3] == 'both')} both)")
        written.append(pid)
    # verify what was written: header, rectangularity, no duplicate ids, every cited experiment present
    for pkg in pkgs:
        out = pkg / "experiment_registry.csv"
        if not out.is_file():
            continue
        rr = [r for r in csv.reader(io.StringIO(out.read_text(encoding="utf-8"))) if r]
        assert rr[0][:len(hdr)] == hdr, f"{pkg.name}: the extract lost the registry's column order"
        assert all(len(r) == len(rr[0]) for r in rr[1:]), f"{pkg.name}: ragged row in the extract"
        ids = [r[0] for r in rr[1:]]
        assert len(ids) == len(set(ids)), f"{pkg.name}: duplicate exp_id in the extract"
        missing = sorted(x for x in cited_experiments(pkg) if x not in set(ids))
        if missing:
            raise SystemExit(f"ABORT: {pkg.name} cites {missing} but the extract does not contain them")
    print("verified: header preserved, rows rectangular, ids unique, every cited experiment present"
          + ("  (--check: nothing written)" if a.check else ""))
    return 2 if (a.check and written) else 0


if __name__ == "__main__":
    sys.exit(main())
