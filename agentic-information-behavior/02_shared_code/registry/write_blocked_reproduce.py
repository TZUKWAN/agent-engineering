"""EXP-0233: give every premise-gated package a reproduce.sh of its own.

A blocked design owes no paper, so it ships no figures, no manuscript and no `reproduce.sh` - and round 2 found that
this left its one substantive claim unreproducible. Each of the 12 gated packages carries an experiment register naming
the runs that decided its gate (P048 cites three: the wave-8 premise census, the turn feature frame and the E-step
battery), and it now also ships the evidence folders holding those runs' outputs (EXP-0231). A reader can therefore
see the numbers behind `BLOCKED.md` but cannot re-derive them, which is the same half-finished claim the estate keeps
finding: a package that looks complete and stops working partway for the next person.

The script writes exactly that: the interpreter probe copied verbatim from a generated package's own `reproduce.sh`
(so there is one copy of it in the estate, and it fails loudly rather than silently differently if that text moves),
then one line per run the package's register names, then the audit that gates every package. It is idempotent - a
package that already has a `reproduce.sh` is left alone - so the closing chain can run it every time.

    python 02_shared_code/registry/write_blocked_reproduce.py [--apply]
"""
from __future__ import annotations

import argparse
import csv
import datetime
import io
import json
import pathlib
import re
import sys
import time

HERE = pathlib.Path(__file__).resolve().parent
ROOT = next(a for a in (HERE, *HERE.parents) if (a / "00_program_registry").is_dir())
REG = ROOT / "00_program_registry" / "experiment_registry.csv"
EXP = "EXP-0233"
PROBE_RX = re.compile(r"(?s)\A(#!/usr/bin/env bash.*?)^cd \"\$ROOT\"\n", re.M)


def interpreter_preamble() -> str:
    """The interpreter-probe block, taken from a package the factory generates.

    Copied rather than re-typed: the estate spent round 2 finding deliverables with two authors, and a second copy of
    this block is how that happens.
    """
    for sh in sorted((ROOT / "papers").glob("P0*/reproduce.sh")):
        m = PROBE_RX.search(sh.read_text(encoding="utf-8", errors="replace"))
        if m:
            return m.group(1) + 'echo "[blocked package] interpreter: $PY"\ncd "$ROOT"\n'
    raise SystemExit("ABORT: no generated reproduce.sh carries the interpreter probe block this script copies")


def register_rows(pkg_dir: pathlib.Path) -> list:
    f = pkg_dir / "experiment_registry.csv"
    if not f.is_file():
        return []
    return list(csv.DictReader(io.StringIO(f.read_text(encoding="utf-8"))))


def script_for(exp_id: str) -> str:
    for r in csv.DictReader(io.StringIO(REG.read_text(encoding="utf-8"))):
        if r["exp_id"] == exp_id:
            return (r.get("script") or "").replace("\\", "/").strip()
    return ""


def body(pkg: pathlib.Path, preamble: str) -> str:
    rows = register_rows(pkg)
    ids = [r.get("exp_id") for r in rows if r.get("exp_id")]
    lines = [line for line in (script_for(e) for e in ids) if line]
    head = (f"#!/usr/bin/env bash\n"
            f"# {pkg.name}: stopped by a pre-registered premise gate, so this package carries no manuscript and no\n"
            f"# analysis of its own. What it does carry is the gate's measurement, and this script re-runs exactly that:\n"
            f"# the {len(lines)} registered run(s) named in this package's `experiment_registry.csv` "
            f"({', '.join(ids[:6])}), then the\n"
            f"# audit every package passes. Generated by\n"
            f"# `02_shared_code/registry/write_blocked_reproduce.py` ({EXP}); re-run that script to refresh it.\n"
            f"set -euo pipefail\n")
    return head + preamble + "\n" + "\n".join(f'"$PY" {s}' for s in lines) + \
        '\n"$PY" 02_shared_code/registry/package_audit.py\n' \
        f'echo "[{pkg.name}] gate re-derived from the runs named in tables/../experiment_registry.csv"\n'


def ensure_row(started: str, finished: str) -> None:
    """Carry this run in the master register before it writes, so the artefact is never its only record."""
    row = {"exp_id": EXP, "paper_id": "programme", "stage": "round2_blocked_package_reproduce_scripts",
           "script": "02_shared_code/registry/write_blocked_reproduce.py",
           "config": "every package under papers/ that ships BLOCKED.md and has no reproduce.sh; the script lines "
                     "come from the runs that package's own register names, so nothing is invented and no analysis is "
                     "re-run by this script itself",
           "seed": "n/a (a maintenance pass over text files)", "started_at": started, "finished_at": finished,
           "status": "reproduce_scripts_written",
           "outputs": "results_raw/EXP0233_blocked_reproduce_scripts_*.json",
           "enters_paper": "no",
           "notes": "round-2: the 12 premise-gated packages shipped BLOCKED.md, a register and the gate's evidence but "
                    "no reproduce.sh, so the decision that stopped each design could be read and not re-derived."}
    rows = list(csv.DictReader(io.StringIO(REG.read_text(encoding="utf-8"))))
    cols = list(rows[0])
    hit = next((r for r in rows if r["exp_id"] == EXP), None)
    if hit is None:
        hit = {c: "" for c in cols}
        hit["exp_id"] = EXP
        rows.append(hit)
    n = 0
    for k, v in row.items():
        if k in cols and hit.get(k) != v:
            hit[k] = v
            n += 1
    if not n:
        return
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=cols, lineterminator=chr(10))
    w.writeheader()
    for r in rows:
        w.writerow({c: str(r.get(c) or "") for c in cols})
    REG.write_text(buf.getvalue(), encoding="utf-8")
    print(f"registry: {EXP} row set ({n} field(s) written)")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true", help="write the scripts (default: report only)")
    a = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    t0 = time.time()
    started = datetime.datetime.now().isoformat(timespec="seconds")
    pre = interpreter_preamble()
    blocked, todo, done = [], [], 0
    for pkg in sorted(p for p in (ROOT / "papers").glob("P0*") if p.is_dir()):
        if not (pkg / "BLOCKED.md").is_file():
            continue
        blocked.append(pkg.name)
        has = (pkg / "reproduce.sh").is_file()
        text = body(pkg, pre)
        if has and (pkg / "reproduce.sh").read_text(encoding="utf-8", errors="replace") == text:
            done += 1
            print(f"{pkg.name[:46]:46s} up to date")
            continue
        todo.append({"package": pkg.name, "existed": has, "runs": len(register_rows(pkg))})
        print(f"{pkg.name[:46]:46s} {'WOULD WRITE' if not a.apply else 'wrote'} "
              f"({len(register_rows(pkg))} registered run(s){'; replaced an existing script' if has else ''})")
        if a.apply:
            f = pkg / "reproduce.sh"
            f.write_text(text, encoding="utf-8")
            f.chmod(0o755)
    finished = datetime.datetime.now().isoformat(timespec="seconds")
    payload = {"exp_id": EXP, "at": finished, "blocked_packages": len(blocked),
               "already_current": done, "written_or_needed": todo,
               "rule": "one line per run the package's own register names; the interpreter probe is copied from a "
                       "generated package rather than duplicated here",
               "wallclock_sec": round(time.time() - t0, 1)}
    out = ROOT / "results_raw" / f"EXP0233_blocked_reproduce_scripts_{time.strftime('%Y%m%dT%H%M%S')}.json"
    if a.apply:
        out.write_text(json.dumps(payload, indent=1, ensure_ascii=False), encoding="utf-8")
        ensure_row(started, finished)
    print(f"{len(blocked)} gated package(s): {done} current, {len(todo)} to write | "
          f"{'wrote ' + out.name if a.apply else 'dry run (--apply to write)'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
