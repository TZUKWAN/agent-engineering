"""Spec item 7 for P001: the pilot report, assembled from EXP-0004/0005/0006 artefacts.

The audit was extended to require a pilot report per paper (P002 and P004 were found to lack one, and P001 turned out
to lack it too even though its pilot is the reason the programme's whole metric convention is opportunity-corrected).
P001's pilot decisions are quoted from `protocol_freeze.md` where they are written, and every number here is read from
the artefact - a missing key aborts the run rather than printing a placeholder.

    python p001_pilot_report.py
"""
from __future__ import annotations

import json, pathlib, re, sys

HERE = pathlib.Path(__file__).resolve().parent          # 02_shared_code/registry
ROOT = HERE.parents[1]
P = ROOT / "papers" / "P001_routing_failure_qpp"


def load(pat):
    f = sorted((ROOT / "results_raw").glob(pat))
    if not f:
        raise SystemExit(f"ABORT: {pat} not found; the pilot report cannot be written from memory")
    return f[-1], json.loads(f[-1].read_text(encoding="utf-8"))


def need(d, *keys):
    for k in keys:
        if k in d:
            return d[k]
    raise SystemExit(f"ABORT: none of {keys} in the artefact (keys present: {list(d)[:12]})")


def quote_from_protocols(*phrases):
    """Pull the frozen rules out of protocol_freeze.md verbatim instead of restating them."""
    txt = (P / "protocol_freeze.md").read_text(encoding="utf-8")
    out = []
    for line in txt.splitlines():
        for ph in phrases:
            if ph in line:
                out.append(line.strip())
    return out


def rnd_mean(v):
    """`dev_baselines['B0_random']` is a {mean, ci95, n} record, not a scalar - reading it as one is what produced a
    'see table-?' placeholder in the first version of this report."""
    if isinstance(v, dict):
        return need(v, "mean")
    return v


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    f4, d4 = load("EXP0004_toucan_retrieval_pilot_*.json")
    cfgs = need(d4, "configs")
    lines, tot = [], {"dev": 0, "test": 0, "kept": 0}
    for name, c in cfgs.items():
        kept, dev, test = need(c, "rows_kept"), need(c, "dev_rows"), need(c, "test_rows")
        tot["kept"] += kept; tot["dev"] += dev; tot["test"] += test
        cpq = c.get("candidates_per_query", {})
        base = c.get("dev_baselines", {})
        rnd = {k: v for k, v in base.items() if "random" in k.lower()}
        rnd_txt = "; ".join(f"{k} hit {rnd_mean(v):.4f} CI {json.dumps(v['ci95']) if isinstance(v, dict) else ''}"
                            for k, v in rnd.items()) or "none recorded"
        bm = {k: v for k, v in base.items() if "bm25" in k.lower()}
        excl = c.get("exclusion_accounting", {})
        lines.append(f"| {name} | {kept:,} | {dev:,} | {test:,} | "
                     f"{cpq.get('mean', cpq.get('median','see artefact'))} | "
                     f"{rnd_txt} | {json.dumps(excl)[:110] or 'none'} |")
    # only the hit@k random baselines belong in that sentence; including B0_random_mrr would quote a range spanning two
    # different measures (hit and reciprocal rank), which is what the first version did
    hit_random = sorted({round(float(rnd_mean(v)), 4) for c in cfgs.values()
                         for k, v in c.get("dev_baselines", {}).items()
                         if "random" in k.lower() and "mrr" not in k.lower()})
    if not hit_random:
        raise SystemExit("ABORT: no random-order baseline in the pilot artefact - the report's key sentence is unsupported")
    b0 = quote_from_protocols("B0 仅查询长度", "随机排序 hit@1")
    b1 = quote_from_protocols("B1 事后准局部 QPP")
    dv = (P / "deviations.md").read_text(encoding="utf-8")
    d1 = next((l.strip() for l in dv.splitlines() if l.startswith("| D1 ")), "")
    sizes = quote_from_protocols("pilot 实际规模")

    body = f"""# Pilot report (P001) - EXP-0004, assembled {pathlib.Path(__file__).name and ''}from the artefact

Spec item 7: what the pilot was for, what it measured, and which decisions it bound. Generated by
`02_shared_code/registry/p001_pilot_report.py` from `{f4.name}`; started {d4['started_at']}, {d4['wallclock_sec']} s,
seed {d4['seed']}, {d4['rows_requested_per_config']:,} rows requested per config.

## Purpose, fixed before the pilot ran

The pilot existed to answer three things and nothing else: whether a gold tool can be joined to the per-query
catalogue at all, how large and how skewed the candidate sets are, and what a **chance** retriever scores on them.
The third question is the one that changed the programme.

## What it measured

| config | rows kept | dev rows | test rows (never evaluated) | mean candidates/query | random-order baselines | exclusion accounting |
|---|---|---|---|---|---|---|
{chr(10).join(lines)}

Totals: {tot['kept']:,} rows joined, {tot['dev']:,} dev, {tot['test']:,} held out for test. Sizes as registered in the
frozen protocol: {sizes[0] if sizes else 'see protocol_freeze.md'}

**The decisive reading: random ordering already hits gold@1 at {min(hit_random):.2f}-{max(hit_random):.2f}** (per-config
values in the table above). A raw hit-rate claim on this corpus would have been mostly chance, which is why the
protocol states:

> {b0[0] if b0 else 'see protocol_freeze.md line on the random-order finding'}

and fixes the baseline ladder the main experiment must beat:

> {b1[0] if b1 else 'see protocol_freeze.md B1 line'}

## What the pilot got wrong, and how that was handled

The first join was a name-prefix heuristic and it over-rejected real rows - recorded, not repaired quietly:

> {d1[:400] if d1 else 'see deviations.md D1'}

That defect (and the failed EXP-0013 rebuild attempts, and EXP-0002's 0.0 parse rate) stay in
`00_program_registry/experiment_registry.csv`; the pilot's negative findings are part of the record, not raw material
for a cleaner story.

## Decisions the pilot bound for the main experiment

1. **Opportunity correction is mandatory** for every hit-rate comparison (the random-order result above);
2. the primary metric stays hit@k on the **dev** split only - test rows were counted here and never scored, and the
   single-use ledger still records exactly one test evaluation;
3. the baseline ladder B0 (query length) and B1 (post-retrieval margin) are the reference points, both measured on
   pilot rows first;
4. per-config reporting rather than pooling, because the three configs differ in candidate-set scale
   (means in the table above).
"""
    out = P / "pilot_report.md"
    bad = [t for t in ("see table", "see artefact", "? ", " -?") if t in body]
    if bad or "?" in body.replace("？", ""):
        raise SystemExit(f"ABORT: the generated report still contains placeholder text {bad}; refusing to deliver it")
    if out.is_file() and "assembled" in out.read_text(encoding="utf-8")[:400]:
        print("pilot_report.md already present - rewriting from the artefact anyway (regenerable)")
    out.write_text(body, encoding="utf-8", newline="")
    print(f"wrote {out} ({len(body.split())} words) from {f4.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
