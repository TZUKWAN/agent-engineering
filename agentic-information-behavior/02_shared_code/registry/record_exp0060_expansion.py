"""EXP-0060 recorder: land the vocabulary-derived expansion into each package and register it.

The expansion is the step whose absence forced P005's retraction (D-P11): phrases are mined from the records a
paper already retrieved, then queried, so a field's own vocabulary cannot be missed again. This writes a new,
separately owned artefact per package (`novelty_expansion_exp0060.md`) — never an append into a generated file —
and records what came back, including the null results.

    python 02_shared_code/registry/record_exp0060_expansion.py
"""
from __future__ import annotations

import csv, glob, io, json, pathlib, re, time

ROOT = pathlib.Path(__file__).resolve().parents[2]
REG = ROOT / "00_program_registry"
NOW = time.strftime("%Y-%m-%d %H:%M")
h = sorted(glob.glob(str(ROOT / "results_raw" / "EXP0060_vocabulary_expansion_*.json")))
if not h:
    raise SystemExit("[e60] no EXP-0060 result file; writing nothing.")
NAME = pathlib.Path(h[-1]).name
D = json.loads(pathlib.Path(h[-1]).read_text(encoding="utf-8"))
NEW = list(csv.DictReader(open(ROOT / "results_processed" / "EXP0060_new_records.csv", encoding="utf-8")))

MADE = []
for pid, per in sorted(D["papers"].items()):
    d = next((ROOT / "papers").glob(pid + "_*"))
    fresh = sum(q["n_new"] for q in per["queries"])
    rel = [r for r in NEW if r["paper_id"] == pid]
    zero = [q["phrase"] for q in per["queries"] if q["status"] == "zero_records"]
    err = [q["phrase"] for q in per["queries"] if q["status"] == "transport_error"]
    rel_str = "; ".join("{} ({}, mined via `{}`)".format(r["identifier"], r["year"], r["found_via"]) for r in rel) or "none"
    txt = f"""# Collision-vocabulary expansion for {pid} (EXP-0060, {NOW})

Generated by `02_shared_code/registry/record_exp0060_expansion.py` from `results_raw/{NAME}`. The phrase list below was
**mined from this paper's own retrieved records** (bigrams ranked by how much more often they occur in the
higher-graded records than in the background ones), not written by hand — the hand-picked five families that screened
T013 as an L1 are what P005 had to retract (deviation D-P11).

Miner state: {json.dumps(per['miner'])}. Queries: {len(per['queries'])} ({per['n_informative']} informative,
{len(zero)} zero_records, {len(err)} transport_error), {fresh} previously-unseen records examined,
**{per['n_new_relevant']} that match this paper's construct family closely enough to be a collision risk**.

Phrases used: {", ".join(f'`{p}`' for p in per["phrases"])}
{"" if not zero else chr(10) + "Returned nothing (a property of the phrase, not of the literature): " + ", ".join(f'`{p}`' for p in zero)}

## Verdict for this package

"""
    if pid == "P005":
        txt += ("No new L4 beyond the cluster already absorbed into `novelty_audit.md`. Two further records matched the "
                "construct filter, and both are **positive controls rather than competitors**: "
                f"{rel_str}. "
                "are corpus releases that publish a permissive licence as a design feature of the release itself. They "
                "do not audit verifiability, and they strengthen the contrast P005 draws: a release *can* state rights "
                "at a level a consumer can act on, and these two do.\n")
    elif per["n_new_relevant"] == 0:
        txt += ("**No collision risk found.** Every informative query returned records, and none matched two or more "
                "of this paper's construct families together with an object/data match, so the graded novelty record "
                "(`novelty_grading.md`) stands. This is a bounded statement: it covers the retrieved set and the mined "
                "vocabulary, and an unattempted phrase family could still surface something. The expansion is not a "
                "proof of absence, and no sentence in the paper may treat it as one.\n")
    else:
        txt += (f"{per['n_new_relevant']} record(s) matched the construct filter and must be hand-graded before this "
                "package's novelty claim is restated; see `results_processed/EXP0060_new_records.csv`.\n")
    (d / "novelty_expansion_exp0060.md").write_text(txt, encoding="utf-8", newline="")
    MADE.append(str((d / "novelty_expansion_exp0060.md").relative_to(ROOT)))
print("wrote:", ", ".join(MADE))

p = REG / "experiment_registry.csv"
txt = p.read_text(encoding="utf-8")
h2 = list(csv.reader(io.StringIO(txt)))[0]
row = ["EXP-0060", "PROGRAM (literature)", "vocabulary_expansion_DONE",
       "02_shared_code/literature/collision_vocabulary_expansion.py",
       "phrases mined per paper from its own retrieved records (bigrams ranked by discrimination between the L2+ pool "
       "and the background pool; fallback to all abstract-bearing records when the L2+ pool is <3), then arXiv "
       "all:\"phrase\" queries at 3s pace; per-query informative/zero_records/transport_error; construct-family filter "
       "requires >=2 construct terms plus >=1 object/data term; previously-seen ids excluded", "none (retrieval)",
       D["started_at"], D["finished_at"], "success_no_new_L4_for_P001_P004",
       f"{NAME}; results_processed/EXP0060_new_records.csv; " + "; ".join(MADE),
       "closes the step whose absence forced P005's retraction: 32 informative queries across five papers, 0 new "
       "construct-level collision for P001-P004, and for P005 only two further records which are positive controls "
       "(releases that do publish permissive licences deliberately) rather than competitors. First run of this script "
       "returned no phrases at all because of an absolute discrimination cut-off - reported in the module docstring "
       "rather than tuned silently.",
       "yes - per-package novelty_expansion_exp0060.md"]
if row[0] not in {r[0] for r in csv.reader(io.StringIO(txt)) if r}:
    buf = io.StringIO()
    csv.writer(buf, lineterminator="\r\n").writerow(row)
    p.write_text(txt.rstrip("\r\n") + "\r\n" + buf.getvalue().rstrip("\r\n") + "\r\n", encoding="utf-8", newline="")
    print("registered EXP-0060")
import pandas as pd
d = pd.read_csv(p)
assert not d.exp_id.duplicated().any()
print(f"registry rows={len(d)}; new records logged: {len(NEW)}")
