"""EXP-0082 (E08 external arm): transfer of the frozen pre-retrieval model to an INDEPENDENT tool universe - ToolRet.

EXP-0021/0022/0023 could only reach corpora that were already on this disk, and only `hermes` carried a per-query
candidate catalogue, which is why P001's external-validation gate stayed open. EXP-0081 then measured that the
benchmark's HuggingFace release is in fact downloadable from this host, so this step ingests it and asks the same
frozen question on a genuinely different tool universe:

    does the frozen P001 predictor rank ToolRet rows that BM25 will miss in its top 3 above rows it will hit?

Two arms, with the primary fixed before any AUROC was computed:

  * **arm A - `query`**, the raw user instruction. This is the clean external test;
  * arm B - `prompt`, the benchmark's own rewritten retrieval instruction. The paper states these instructions are
    generated by a **target-aware** strategy and the released example literally names the capabilities of the gold
    tools ("retrieve tools that can provide straddle data for a given stock ticker"), so arm B can only be reported
    as a leakage-bounded upper reference, never as the headline.

Construct differences that are measured and disclosed rather than smoothed over:

  * the per-query candidate set here is **10 hard negatives mined by NV-embed-v1 plus the targets** (paper §4), not a
    production catalogue, so fail@3 is defined against a denser, deliberately harder set than Toucan's and the
    prevalence is not comparable to the published 0.1777;
  * because the negatives were mined by a retrieval model, the DV is entangled with a retriever's difficulty notion -
    the arm-A number is therefore reported next to a length-only baseline on the same rows and a post-retrieval
    margin baseline, both labelled as what they are;
  * `n_candidates` is near-constant by construction, so any frozen feature that measures catalogue size is degenerate
    here; the step reports the spread rather than dropping the feature quietly.

Verdict bands are the ones frozen in EXP-0021: AUROC >= 0.65 transfers, 0.55-0.65 partial, < 0.55 does not transfer.
Nothing is fitted on ToolRet rows: they are scored only, and no feature, threshold or C value was chosen from them.

    python toolret_external_transfer_e08.py [--rows 6000] [--seed 20260920]

Outputs results_raw/EXP0082_toolret_external_transfer_*.json and
        results_processed/EXP0082_toolret_*.csv
"""
from __future__ import annotations

import argparse, json, pathlib, sys, time
from collections import Counter

import numpy as np
import pandas as pd
import pyarrow.parquet as pq
from sklearn.metrics import roc_auc_score
from sklearn.model_selection import StratifiedKFold

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent / "trajectory_parser"))
from analyze_routing_failure import CONFIGS, PROC, SEEDS, oof_auc, scaled_pipeline   # noqa: E402
from build_toucan_routing_dataset import (BM25, collection_qpp_features, hyper_chance,  # noqa: E402
                                          question_features, toks)
from run_p001_experiments import FROZEN_C, FROZEN_FEATURES, matrices                  # noqa: E402

ROOT = HERE.parents[1]
SHARD = ROOT / "01_datasets" / "raw" / "toolret" / "ToolRet-Training-20w" / "train-00000-of-00006.parquet"
OUT_RAW = ROOT / "results_raw"
OUT_PROC = ROOT / "results_processed"
K = 3
DV = "fail_at_3"
BANDS = {"transfers": 0.65, "partial": 0.55}


def tool_docs(blob_list, stat):
    """ToolRet stores each tool as a JSON *string*, and the release merges ~20 upstream sources so two dialects occur
    in the same column: `name/description/parameters{...}` and
    `api_name|name / api_description|description / required_parameters[]+optional_parameters[]`. Both are read, and a
    blob that yields no name is counted as a rejection rather than passed through as an empty tool."""
    out = []
    for s in ([] if blob_list is None else list(blob_list)):
        try:
            d = json.loads(s) if isinstance(s, str) else dict(s)
        except (json.JSONDecodeError, TypeError):
            stat["reject_tool_blob_unparseable"] += 1
            continue
        name = str(d.get("name") or d.get("api_name") or "").strip()
        if not name:
            stat["reject_tool_blob_no_name"] += 1
            continue
        stat["dialect_parameters_dict"] += 1 if isinstance(d.get("parameters"), dict) else 0
        stat["dialect_required_optional_lists"] += 1 if (d.get("required_parameters") or d.get("optional_parameters")) else 0
        desc = str(d.get("description") or d.get("api_description") or "")
        pars = d.get("parameters")
        keys = [str(x) for x in pars] if isinstance(pars, dict) else []
        for lst in (d.get("required_parameters"), d.get("optional_parameters")):
            if isinstance(lst, list):
                keys += [str(p.get("name")) for p in lst if isinstance(p, dict) and p.get("name")]
        out.append({"name": name, "desc": desc, "params": keys})
    return out


def build(rows_want: int, seed: int) -> tuple[pd.DataFrame, dict]:
    """One arm per question rendering; the catalogue, gold indices and BM25 ranks are shared by both."""
    stat = Counter()
    tbl = pq.read_table(SHARD, columns=["id", "query", "prompt", "positive", "negative"])
    df = tbl.to_pandas()
    stat["rows_in_shard"] = int(len(df))
    rng = np.random.default_rng(seed)
    take = rng.permutation(len(df))[:rows_want] if rows_want < len(df) else np.arange(len(df))
    bm = BM25(k1=1.4, b=0.4)
    kept = []
    for i in take:
        r = df.iloc[int(i)]
        pos = tool_docs(r["positive"], stat)
        neg = tool_docs(r["negative"], stat)
        catalog = pos + neg
        if not catalog:
            stat["reject_catalog_empty"] += 1
            continue
        if not pos:
            stat["reject_no_positive"] += 1
            continue
        gold_names = {d["name"] for d in pos}
        idx = sorted({j for j, d in enumerate(catalog) if d["name"] in gold_names})
        if not idx:
            stat["reject_gold_not_in_own_catalog"] += 1
            continue
        q = str(r["query"] or "").strip()
        ins = str(r["prompt"] or "").strip()
        if not q:
            stat["reject_empty_instruction"] += 1
            continue
        docs_full = [toks(d["name"].replace("-", " ").replace("_", " ")) + toks(d["desc"])
                     + toks(" ".join(d["params"])) for d in catalog]
        n_c = len(catalog)
        rec = {"cfg": "TOOLRET", "subset_name": "toolret_train_20w", "prompt_id": str(r["id"]),
               "split": "external", "n_gold": len(idx), "gold_idx": json.dumps(idx),
               "n_servers_in_row": 0,
               "catalog_json": json.dumps([{"n": d["name"], "d": d["desc"], "p": d["params"]} for d in catalog],
                                          ensure_ascii=False)}
        # arm A/B differ ONLY in the text the frozen feature functions see
        for arm, text in (("query", q), ("instruction", ins or q)):
            qtok = toks(text)
            sc = bm.scores(qtok, docs_full)
            ranked = sorted(range(len(sc)), key=lambda j: -sc[j])
            rb = min((ranked.index(j) + 1 for j in idx), default=n_c)
            srt = sorted(sc, reverse=True)
            margin = (srt[0] - srt[1]) if len(srt) > 1 else (srt[0] if srt else 0.0)
            common = {"n_candidates": n_c, "bm25_best_rank": rb,
                      "bm25_top1_score": round(max(sc) if sc else 0.0, 6), "bm25_margin": round(margin, 6),
                      "norm_rank": (rb - 1) / max(1, n_c - 1),
                      "fail_at_1": int(rb > 1), "fail_at_3": int(rb > 3), "fail_at_5": int(rb > 5),
                      "chance_hit_1": hyper_chance(len(idx), n_c, 1),
                      "chance_hit_3": hyper_chance(len(idx), n_c, 3),
                      "chance_hit_5": hyper_chance(len(idx), n_c, 5)}
            for c, v in common.items():
                rec[f"{arm}_{c}"] = v
            rec[f"{arm}_question"] = text[:4000]
            for c, v in collection_qpp_features(qtok, docs_full).items():
                rec[f"{arm}_{c}"] = v
            for c, v in question_features(text).items():
                rec[f"{arm}_{c}"] = v
        kept.append(rec)
    out = pd.DataFrame(kept)
    # the frozen feature names refer to the plain columns, so each arm gets its own frame
    arms = {}
    for arm in ("query", "instruction"):
        a = out.copy()
        for c in out.columns:
            if c.startswith(arm + "_"):
                a[c[len(arm) + 1:]] = a[c]
            elif c.startswith(("query_", "instruction_")):
                pass          # leave the other arm's prefixed columns alone; they are unused
        a["question"] = a[f"{arm}_question"]
        arms[arm] = a.drop(columns=[c for c in out.columns if c.endswith("_question")], errors="ignore")
    return arms, dict(stat)


def verdict(auc: float) -> str:
    return "transfers" if auc >= BANDS["transfers"] else ("partial" if auc >= BANDS["partial"] else "does not transfer")


def score(arm_df: pd.DataFrame, src: pd.DataFrame, tag: str, log):
    """Fit on the published Toucan dev rows only; score ToolRet. Same matrices(), same C, no tuning here."""
    Xs = matrices(src, FROZEN_FEATURES)["all"]
    model = scaled_pipeline(FROZEN_C)().fit(Xs, src[DV].values.astype(int))
    X = matrices(arm_df, FROZEN_FEATURES)["all"]
    y = arm_df[DV].values.astype(int)
    p = model.predict_proba(X)[:, 1]
    auc = float(roc_auc_score(y, p))
    rng = np.random.default_rng(SEEDS[0])
    boots = [roc_auc_score(y[i], p[i]) for i in
             (rng.integers(0, len(y), size=(len(y),)) for _ in range(500)) if 0 < y[i].sum() < len(i)]
    lo, hi = (float(np.percentile(boots, 2.5)), float(np.percentile(boots, 97.5))) if boots else (None, None)
    length_only = float(roc_auc_score(y, -arm_df["n_chars"].values)) if "n_chars" in arm_df else None
    within = [oof_auc(X, y, scaled_pipeline(FROZEN_C), s)[0] for s in SEEDS]
    res = {"arm": tag, "n_rows": int(len(arm_df)), "positives": int(y.sum()),
           "fail_at_3_prevalence": round(float(y.mean()), 4),
           "frozen_auroc": round(auc, 4), "row_bootstrap_ci95": [round(lo, 4), round(hi, 4)] if lo else None,
           "verdict_by_frozen_bands": verdict(auc),
           "length_only_baseline": round(length_only, 4) if length_only is not None else None,
           "post_retrieval_margin_baseline": round(float(roc_auc_score(y, -arm_df["bm25_margin"].values)), 4),
           "chance_hit_3_mean": round(float(arm_df["chance_hit_3"].mean()), 4),
           "within_corpus_oof_aucroc": [round(float(v), 4) for v in within],
           "mean_n_candidates": round(float(arm_df["n_candidates"].mean()), 2),
           "sd_n_candidates": round(float(arm_df["n_candidates"].std()), 2),
           "distinct_catalogues": int(arm_df["catalog_json"].nunique())}
    log(f"  {tag}: n={res['n_rows']} fail@3={res['fail_at_3_prevalence']} AUROC={res['frozen_auroc']} "
        f"CI={res['row_bootstrap_ci95']} -> {res['verdict_by_frozen_bands']} "
        f"(length-only {res['length_only_baseline']}, margin {res['post_retrieval_margin_baseline']})")
    return res


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--rows", type=int, default=6000)
    ap.add_argument("--seed", type=int, default=20260920)
    args = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")
    t0 = time.time()
    if not SHARD.is_file():
        raise SystemExit(f"ABORT: shard not on disk ({SHARD}); run the download step first")
    exp = {"exp_id": "EXP-0082", "e_id": "E08", "seed": args.seed, "k": K, "dv": DV,
           "frozen_model": {"C": FROZEN_C, "n_features": len(FROZEN_FEATURES or []),
                            "features_file": "papers/P001_routing_failure_qpp/configs/P001_frozen_model.json"},
           "bands": BANDS, "source_shard": str(SHARD), "rows_requested": args.rows,
           "started_at": time.strftime("%Y-%m-%dT%H:%M:%S")}
    exp["acquisition_provenance"] = {
        "repo": "mangopy/ToolRet-Training-20w", "channel": "hf-mirror via huggingface_hub (EXP-0081 verified)",
        "revision": "fdf5a317455b1e60785de7ba6078f4...snapshot id from the HF cache",
        "card_declares": {"splits": 1, "num_examples": 208826, "download_size_bytes": 920232186},
        "shard_bytes_on_disk": int(SHARD.stat().st_size)}

    arms, stat = build(args.rows, args.seed)
    exp["corpus_extraction"] = {"rows_seen": stat.get("rows_in_shard", 0), "rows_sampled": args.rows,
                                "rows_kept": int(len(arms["query"])),
                                "rejection_accounting": {k: v for k, v in sorted(stat.items())
                                                         if k.startswith("reject_")}}
    inc = arms["query"].n_candidates > K
    exp["inclusion_rule"] = {"rule": f"n_candidates > {K}", "rows_kept": int(inc.sum()),
                             "rows_dropped": int((~inc).sum())}
    arms = {a: d[inc.values].reset_index(drop=True) for a, d in arms.items()}
    exp["hard_negative_construct"] = {
        "negatives_per_query": sorted(Counter((arms["query"].n_candidates - arms["query"].n_gold)).items())[:4],
        "note": "the benchmark mines 10 negatives per query with NV-embed-v1, so this candidate set is a mined hard-"
                "negative set, not a production catalogue; fail@3 prevalence here is not comparable to Toucan's 0.1777"}
    log = lambda *a: print(*a, flush=True)
    log(f"  rows kept={len(arms['query'])} of {args.rows} sampled; n_candidates mean="
        f"{arms['query'].n_candidates.mean():.2f} sd={arms['query'].n_candidates.std():.2f}")

    src = pd.concat([pd.read_parquet(PROC / f"routing_{c}.parquet") for c in CONFIGS], ignore_index=True)
    src = src[(src.split == "dev") & (src.n_candidates > K)].reset_index(drop=True)
    assert not set(src.prompt_id) & set(arms["query"].prompt_id), "an id appears in both source and external rows"
    exp["source"] = {"n_dev_rows": int(len(src)), "configs": list(CONFIGS),
                     "fail_at_3_prevalence": round(float(src[DV].mean()), 4)}

    exp["arms"] = [score(arms[a], src, a, log) for a in ("query", "instruction")]
    primary = exp["arms"][0]

    # independence audit, the same question EXP-0023 asked of hermes
    src_names = {d["n"] for cj in src.catalog_json for d in json.loads(cj)}
    ext_names = {d["n"] for cj in arms["query"].catalog_json for d in json.loads(cj)}
    ext_tok = {t for cj in arms["query"].catalog_json for d in json.loads(cj)
               for t in toks((d["n"] + " " + d["d"]).lower())}
    src_tok = {t for cj in src.catalog_json for d in json.loads(cj) for t in toks((d["n"] + " " + d["d"]).lower())}
    exp["independence"] = {
        "external_tool_names": len(ext_names), "source_tool_names": len(src_names),
        "shared_tool_names": len(ext_names & src_names),
        "share_of_external_names_unseen_in_source": round(1 - len(ext_names & src_names) / max(1, len(ext_names)), 4),
        "external_catalog_tokens_covered_by_source": round(len(ext_tok & src_tok) / max(1, len(ext_tok)), 4),
        "distinct_catalogues_external": primary["distinct_catalogues"]}
    log(f"  independence: {exp['independence']['shared_tool_names']}/{len(ext_names)} tool names shared with the "
        f"source corpora; token coverage {exp['independence']['external_catalog_tokens_covered_by_source']}")

    exp["what_this_answers"] = (
        "arm A is the first transfer of the frozen predictor to a tool universe assembled by other people from other "
        "datasets; " + verdict(primary["frozen_auroc"]) + " at AUROC "
        f"{primary['frozen_auroc']} (row bootstrap {primary['row_bootstrap_ci95']}) against the frozen bands "
        ">=0.65 / 0.55-0.65 / <0.55")
    exp["what_this_does_not_answer"] = [
        "the benchmark's own held-out evaluation split: these rows are its TRAINING partition, so a model could "
        "memorise them - irrelevant here because nothing was fitted on them, but it means this is not a leaderboard "
        "reproduction",
        "whether ToolRet's nDCG@10 numbers agree with P001's hit@3 numbers: different measures, different candidate "
        "sets, and the paper's corpus is a mined negative set rather than a catalogue",
        "arm B as a headline: the released instructions are target-aware, so any gain from them is leakage-bounded",
        "a catalogue-clustered interval: every row carries its own mined negative set "
        f"({primary['distinct_catalogues']} distinct catalogues over {primary['n_rows']} rows), so the interval "
        "reported is row-level and is labelled as such"]
    pd.DataFrame(exp["arms"]).T.to_csv(OUT_PROC / "EXP0082_toolret_arms.csv")
    arms["query"].head(50).to_csv(OUT_PROC / "EXP0082_toolret_rows_sample.csv", index=False)
    exp["wallclock_sec"] = round(time.time() - t0, 1)
    OUT_RAW.mkdir(parents=True, exist_ok=True)
    fp = OUT_RAW / f"EXP0082_toolret_external_transfer_{time.strftime('%Y%m%dT%H%M%S')}.json"
    fp.write_text(json.dumps(exp, indent=1, ensure_ascii=False), encoding="utf-8", newline="")
    log(f"  wrote {fp.name} in {exp['wallclock_sec']}s")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
