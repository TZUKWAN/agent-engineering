"""Figure generators for the wave packages: every figure a package ships is drawn here from its own tables.

Spec 15 plans eight roles per paper and spec 0 ships "all figures of the paper"; both are only satisfied if a figure
is a real artefact whose data path is known. Each function therefore reads a CSV that an experiment wrote, and each
caption names the generator and the table it came from, so `package_audit`'s citation guard and the rebuild chain can
both resolve it. No figure is drawn from a number typed into this file.

    python 02_shared_code/package_factory/wave_figures.py --pkg P006 --topic T101
"""
from __future__ import annotations

import argparse
import pathlib
import sys

import numpy as np
import pandas as pd

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import wave_lib as W                                              # noqa: E402

GEN = "02_shared_code/package_factory/wave_figures.py"


def _read(pkg: str, name: str) -> pd.DataFrame:
    for base in (W.ROOT / "papers" / pkg / "tables", W.PROCES):
        f = base / name
        if f.is_file():
            return pd.read_csv(f)
    raise FileNotFoundError(f"{name} for {pkg}: not in the package tables nor results_processed - "
                            f"a figure cannot be drawn from a table that does not exist")


def _finish(fig, outdir: pathlib.Path, name: str, caption: str) -> dict:
    r = W.save_fig(fig, outdir, name, caption + f"\n\nGenerated by {GEN}; no value in this figure is typed by hand.")
    print(f"  {name}  ({r['bytes'][0]} bytes pdf)")
    return r


def forest(ax, df, xcol, lo, hi, lab, title, xlabel, ref=0.0):
    # a model table whose rows are rates, shares or cross-validated statistics may legitimately carry no interval at
    # all; the figure then plots the point estimates it can and must not stop the whole build
    for c in (xcol, lo, hi):
        if c not in df.columns:
            df = df.assign(**{c: np.nan})
    # a shipped table now writes "not_recorded" where a value is absent, so that the reviewer can tell an
    # unrecorded quantity from a lost one; for the plot both mean the same thing - nothing to draw - so the
    # columns are coerced before the drop rather than assumed numeric
    for c in (xcol, lo, hi):
        df[c] = pd.to_numeric(df[c], errors="coerce")
    df = df.dropna(subset=[xcol, lo, hi])
    y = np.arange(len(df))[::-1]
    ax.errorbar(df[xcol], y, xerr=[df[xcol] - df[lo], df[hi] - df[xcol]], fmt="o", color="#1f4e79",
                capsize=3, lw=1.4)
    ax.axvline(ref, color="#999999", ls="--", lw=1)
    ax.set_yticks(y)
    ax.set_yticklabels([str(t)[:46] for t in df[lab]], fontsize=7.5)
    ax.set_xlabel(xlabel, fontsize=8)
    ax.set_title(title, fontsize=9)
    ax.grid(axis="x", alpha=.25)
    return len(df)


def framework(ax, design: dict, topic: str):
    """The design's own causal chain as written in the freeze: language -> mechanism -> measured outcome."""
    ax.axis("off")
    boxes = [("instruction language\n" + ", ".join(list(design["features"])[:3]), "#dbeafe"),
             ("machine relevance / search\n" + ", ".join(list(design["dvs"])[:3]), "#dcfce7"),
             ("outcome under the frozen ranker\n" + design["models"][0][:56], "#fef9c3")]
    for i, (txt, col) in enumerate(boxes):
        x = 0.03 + i * 0.325
        ax.add_patch(plt_box(x, 0.35, 0.29, 0.3, txt, col))
        if i:
            ax.annotate("", xy=(x - 0.015, 0.5), xytext=(x - 0.045, 0.5),
                        arrowprops=dict(arrowstyle="->", lw=1.3, color="#333333"))
    ax.text(0.03, 0.78, f"{topic} - {design['title']}", fontsize=9.5, weight="bold")
    ax.text(0.03, 0.16, "Hypotheses: " + " | ".join(h.split(" ")[0] for h in design["hypotheses"]),
            fontsize=7.5, color="#444444")
    ax.text(0.03, 0.07, "Kill gate: " + design["kill_gate"][:150], fontsize=7, color="#7a2e2e")
    ax.set_xlim(0, 1); ax.set_ylim(0, 1)


def plt_box(x, y, w, h, text, color):
    from matplotlib.patches import FancyBboxPatch
    return FancyBboxPatch((x, y), w, h, boxstyle="round,pad=0.012,rounding_size=0.02",
                          linewidth=0.9, edgecolor="#555555", facecolor=color)


def wrap(ax, text, x=0.02, y=0.97, fontsize=7.2, width=118):
    import textwrap
    ax.text(x, y, "\n".join(textwrap.wrap(str(text), width)), fontsize=fontsize, va="top", family="monospace")


def build(pkg: str, topic: str, design: dict, outdir: pathlib.Path) -> list:
    plt, _ = W.new_fig()
    outdir.mkdir(parents=True, exist_ok=True)
    made = []
    for name in design["figures"]:
        kind = name.replace(".pdf", "").split("_", 1)[-1]
        fig, ax = plt.subplots(figsize=(7.0, 4.3))
        if name.startswith("fig0"):
            framework(ax, design, topic)
            cap = (f"Figure 0. Design map for {topic}: the linguistic features frozen before any outcome was read, "
                   f"the measured outcomes, and the kill gate that would have stopped the design.")
        elif name.startswith("fig1"):
            try:
                t = _read(pkg, "table2_" + [f for f in design["tables"] if f.startswith("table2_")][0][7:]) \
                    if any(f.startswith("table2_") for f in design["tables"]) else None
            except Exception:                                     # noqa: BLE001
                t = None
            if t is None:
                t = _read(pkg, [f for f in design["tables"] if f.startswith("table2")][0])
            num = [c for c in t.columns if str(t[c].dtype).startswith(("int", "float"))]
            if num:
                ax.barh(range(len(t)), t[num[0]].astype(float), color="#8fb8de")
                ax.set_yticks(range(len(t)))
                ax.set_yticklabels([str(v)[:40] for v in t[t.columns[0]]], fontsize=7)
                ax.set_xlabel(str(num[0]), fontsize=8)
            else:
                wrap(ax, t.to_string(index=False)[:2400])
            cap = f"Figure 1. Distribution / example panel, from {pkg}/tables/table2_*.csv."
        elif name.startswith("fig2"):
            t = _read(pkg, [f for f in design["tables"] if f.startswith("table3")][0])
            if "beta" in t.columns:
                n = forest(ax, t, "beta", "ci_lo", "ci_hi", "term",
                           f"{topic}: pre-registered effects (cluster-robust 95% CI)", "coefficient")
            elif "inspected" in t.columns:
                ax.plot(t.iloc[:, 0], t["inspected"], "o-", color="#1f4e79")
                ax.set_xlabel("constraint decile"); ax.set_ylabel("mean candidates inspected")
            else:
                wrap(ax, t.to_string(index=False)[:2400])
            cap = f"Figure 2. Main result panel for {topic}, from tables/table3_*.csv."
        elif name.startswith("fig3"):
            tab = [f for f in design["tables"] if f.startswith("table4")]
            t = _read(pkg, tab[0]) if tab else _read(pkg, [f for f in design["tables"] if f.startswith("table6")][0])
            num = [c for c in t.columns if str(t[c].dtype).startswith(("int", "float"))]
            if len(num) >= 2:
                ax.bar(range(len(t)), t[num[0]].astype(float), color="#a8d5a2", label=num[0])
                ax.bar(np.arange(len(t)) + 0.28, t[num[1]].astype(float), color="#f0b27a", label=num[1])
                ax.set_xticks(np.arange(len(t)) + 0.14)
                ax.set_xticklabels([str(v)[:24] for v in t[t.columns[0]]], fontsize=7, rotation=20)
                ax.legend(fontsize=7)
            else:
                wrap(ax, t.to_string(index=False)[:2400])
            cap = f"Figure 3. Mechanism / stratum panel for {topic}, from tables/table4_*.csv."
        elif name.startswith("fig4"):
            tab = [f for f in design["tables"] if f.startswith("table5")]
            t = _read(pkg, tab[0]) if tab else _read(pkg, [f for f in design["tables"]
                                                           if f.startswith("table6")][0])
            if {"beta", "ci_lo", "ci_hi"} <= set(t.columns):
                forest(ax, t, "beta", "ci_lo", "ci_hi",
                       t.columns[0], f"{topic}: robustness variants against the frozen rule", "coefficient")
            else:
                wrap(ax, t.to_string(index=False)[:2400])
            cap = f"Figure 4. Robustness panel for {topic}: every variant the freeze allows, on one axis."
        elif name.startswith("fig5"):
            # The §15 "headline by config" role: the frozen coefficient estimated inside each corpus config, read
            # from the battery's own per-config block. Configs the block reports as not estimable stay in the
            # caption as counts rather than being dropped from the axis.
            t = _read(pkg, "table18_headline_by_config.csv")
            ok = t.dropna(subset=["beta"]) if "beta" in t.columns else t.iloc[0:0]
            if ok.empty:
                raise SystemExit(f"ABORT {pkg}: fig5 needs an estimable per-config row in "
                                 f"table18_headline_by_config.csv and the artefact has none - draw the figure "
                                 f"from the measurement or do not ship it")
            n = forest(ax, ok, "beta", "ci_lo", "ci_hi", "config",
                       f"{topic}: the frozen effect within each corpus config", "coefficient (cluster-robust 95% CI)")
            cap = (f"Figure 5. Headline effect estimated separately inside each of the {n} corpus configs with "
                   f"enough rows and query clusters to identify it, from tables/"
                   f"table18_headline_by_config.csv. This is heterogeneity on one shared catalogue text "
                   f"(EXP-0150), not a replication.")
        elif name.startswith("fig6"):
            # The §15 "data schematic" role: the sample the design actually scored, measure by measure, from the
            # package's own structure table. A log axis keeps row counts and token counts on one scale.
            t = _read(pkg, "table1_sample_and_structure.csv")
            num = []
            for _, r in t.iterrows():
                try:
                    v = float(r["value"])
                except (TypeError, ValueError, KeyError):
                    continue
                if v > 0:
                    num.append((str(r["field"])[:46], v))
            if not num:
                raise SystemExit(f"ABORT {pkg}: fig6 found no positive numeric field in "
                                 f"table1_sample_and_structure.csv - the structure table is empty, so the "
                                 f"figure has no subject")
            ax.set_xscale("log")
            ax.barh([p[0] for p in num][::-1], [p[1] for p in num][::-1], color="#c9b6e4")
            ax.set_xlabel("count (log scale)", fontsize=8)
            ax.set_title(f"{topic}: what the corpus contributes to this design", fontsize=9)
            ax.tick_params(axis="y", labelsize=7.5)
            ax.grid(axis="x", alpha=.25)
            cap = (f"Figure 6. Data-structure panel for {topic}: the {len(num)} counted quantities the package "
                   f"reports about its own sample, from tables/table1_sample_and_structure.csv.")
        else:
            raise SystemExit(f"ABORT {pkg}: figure {name!r} matches no drawing branch. The previous fallback drew "
                             f"every unrecognised role from table5, which is how three of a package's seven "
                             f"figures shipped as byte-identical copies of one robustness panel.")
        fig.tight_layout()
        made.append(_finish(fig, outdir, name, cap))
    return made


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--pkg", required=True)
    ap.add_argument("--topic", required=True)
    ap.add_argument("--design-module", default="topic_designs_wave1")
    a = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")
    import importlib
    dm = importlib.import_module(a.design_module)
    out = W.ROOT / "papers" / a.pkg / "figures"
    res = build(a.pkg, a.topic, dm.DESIGNS[a.topic], out)
    print(f"{a.topic}: {len(res)} figures -> {out}")
