"""EXP-0100: put the sections the spec demands into the manuscripts, assembled from each package's own tables.

EXP-0099's content signatures found three writing requirements the packages met only outside `paper.md`:

* **T16.03/T16.05** - the research questions were frozen in each `research_plan.md` but never stated in the manuscript
  (P003 and P005 read as a sequence of findings with no question attached to them);
* **T16.02/T16.04** - P002's manuscript has no related-work section and no conclusion, although its
  `literature_matrix.csv` carries written differentiations for its neighbours and its claims matrix says which claims
  failed;
* **T16.03** - P004's introduction never names the gap it fills.

This step inserts exactly those sections, generated by `manuscript_sections.py` from the package's own curated rows - no
sentence here is invented, and a package with too few curated rows gets no section rather than a padded one. Idempotent:
each block is keyed on its own first line, so re-running changes nothing. It is wired into every `reproduce.sh` right
after the step that writes that package's `paper.md`, so a clean rebuild produces the same manuscript.

    python 02_shared_code/writing/add_manuscript_sections.py [--paper P002] [--dry-run]
"""
from __future__ import annotations
import argparse, json, pathlib, re, sys, time

HERE = pathlib.Path(__file__).resolve().parent
ROOT = next(a for a in (HERE, *HERE.parents) if (a / "00_program_registry").is_dir())
sys.path.insert(0, str(HERE))
from manuscript_sections import (research_questions, related_work, conclusions, insert_block,   # noqa: E402
                                 g03_one_pager, scope_211)

OUT = ROOT / "results_raw"
# Where each block goes, and for which package. Only the packages EXP-0099 found a requirement missing from are listed:
# P001/P002/P004 already state their questions inside the manuscript, so nothing is inserted there.
# `after_section` = insert at the end of that section; `before_section` = insert as its own section before the anchor.
PLAN = {
    "P002": {"related": ("before_section", "## 2 Frozen instrument"), "concl": ("append",)},
    "P003": {"rq": ("after_section", "## 1 ")},
    "P005": {"rq": ("after_section", "## 1 ")},
}
# Gate G03 is asked of every paper, and every paper's first numbered section is its introduction, so one anchor serves
# all five: the positioning block closes section 1, immediately before the related work or the instrument.
DEFAULT_PLAN = {"g03": ("after_section", "## 1 "), "scope": ("after_section", "## 1 ")}
GAP_SENTENCE = {
    "P004": ("**The gap, stated plainly.** None of the records screened for this paper validates a quality column that "
             "arrives pre-computed inside a released corpus: each evaluates a judge the authors run themselves, with a "
             "prompt they can read, a scale they define and a configuration they can re-run. The measurement properties "
             "of an untraceable shipped score - whether it is a scale, what it tracks, what it is confounded by, and "
             "what filtering on it does to a population - are the part no screened work answers, and they are what "
             "sections 4 to 6 measure."),
}


def end_of_section(text: str, heading: str) -> int:
    """Index just past the body of the section that starts with `heading`, or -1."""
    i = text.find(heading)
    if i < 0:
        return -1
    j = text.find("\n## ", i + len(heading))
    return len(text) if j < 0 else j


def apply_one(pkg_dir: pathlib.Path, pid: str, dry: bool = False):
    pm = pkg_dir / "paper.md"
    text = pm.read_text(encoding="utf-8")
    orig = text
    actions = []
    # An earlier version of `place` cut the previous block at the marker's character offset rather than at the line
    # boundary, which left the line's own opening `**` behind as a line containing nothing but bold markers. Those are
    # this generator's litter, not manuscript content, and removing them here means the fix survives a rebuild.
    litter = len(re.findall(r"(?m)^\*\*\s*$", text))
    if litter:
        text = re.sub(r"(?m)^\*\*\s*\n\n?", "", text)
        actions.append({"block": "_litter", "result": f"removed {litter} stray bold-marker line(s) left by the old cut"})
    plan = dict(DEFAULT_PLAN)
    plan.update(PLAN.get(pid, {}))
    # Every block this generator can place for this package, built before any of them is inserted. Their opening lines
    # are boundaries a removal may not cross: cutting "from my marker to the next `## `" swallowed whatever sibling
    # block had just been appended to the same section, which is how P002's and P004's G03 one-pager disappeared while
    # the step still reported success (the composed text came back byte-identical to the file, so nothing was written).
    OWNED = {b[0].splitlines()[0].replace("**", "").strip()
             for b in (research_questions(pkg_dir), g03_one_pager(pkg_dir), scope_211(pkg_dir),
                       related_work(pkg_dir), conclusions(pkg_dir)) if b and b[0]}

    def place(kind_and_anchor, block, heading):
        """Put `block` where the plan says, replacing any version this generator inserted before.

        The old code stopped when it saw its own first line already in the manuscript, which made an improved block
        impossible to ship: the file would keep the stale text and the step would report success. A previously inserted
        block is now cut out (marker line up to the next boundary - a `## ` heading or another owned block's first line,
        which is exactly where the insertion stopped) and the current block put in its place, so idempotence means
        "the same bytes twice", not "the first bytes forever"."""
        nonlocal text
        marker = block.splitlines()[0].replace("**", "").strip()
        def cut(txt: str) -> str:
            """Remove every copy of a block this generator inserted before. Cutting only the first copy would let the
            duplicates an earlier bug created keep accumulating one section per run."""
            lines = txt.split("\n")
            k = next((idx for idx, ln in enumerate(lines) if marker and marker in ln.replace("**", "")), None)
            if k is None:
                return txt
            if heading:
                prev = next((idx for idx in range(k - 1, -1, -1) if lines[idx].strip()), None)
                if prev is not None and lines[prev].strip() == heading.strip():
                    k = prev                 # the heading this generator wrote belongs to the block
            e = next((idx for idx in range(k + 1, len(lines))
                      if lines[idx].startswith("## ") or lines[idx].replace("**", "").strip() in OWNED), len(lines))
            return cut("\n".join(lines[:k] + lines[e:]).rstrip("\n") + "\n")

        text = cut(text)
        kind = kind_and_anchor[0]
        sec = (heading + "\n\n") if heading else ""
        if kind == "append":
            text = text.rstrip("\n") + "\n\n" + sec + block + "\n"
            return "appended as a final section"
        if kind == "before_section":
            i = text.find(kind_and_anchor[1])
            if i < 0:
                return f"anchor {kind_and_anchor[1]!r} absent - skipped"
            text = text[:i] + sec + block + "\n\n" + text[i:].lstrip("\n")
            return "inserted as its own section before the anchor"
        j = end_of_section(text, kind_and_anchor[1])
        if j < 0:
            return f"anchor {kind_and_anchor[1]!r} absent - skipped"
        text = text[:j].rstrip("\n") + "\n\n" + sec + block + "\n\n" + text[j:].lstrip("\n")
        return "inserted at the end of the anchor section"

    blk, why = research_questions(pkg_dir)
    if "rq" not in plan:
        actions.append({"block": "research_questions", "result": "not requested for this package"})
    elif blk is None:
        actions.append({"block": "research_questions", "result": f"not emitted: {why}"})
    else:
        actions.append({"block": "research_questions", "source": why, "result": place(plan["rq"], blk, "")})
    blk, why = g03_one_pager(pkg_dir)
    if blk is None:
        actions.append({"block": "g03_one_pager", "result": f"not emitted: {why}"})
    else:
        actions.append({"block": "g03_one_pager", "source": why,
                        "result": place(plan["g03"], blk, "")})
    blk, why = scope_211(pkg_dir)
    if blk is None:
        actions.append({"block": "scope_211", "result": f"not emitted: {why}"})
    else:
        actions.append({"block": "scope_211", "source": why, "result": place(plan["scope"], blk, "")})
    blk, why = related_work(pkg_dir)
    if "related" not in plan:
        actions.append({"block": "related_work", "result": "not requested for this package"})
    elif blk is None:
        actions.append({"block": "related_work", "result": f"not emitted: {why}"})
    else:
        actions.append({"block": "related_work", "source": why,
                        "result": place(plan["related"], blk, "## Related work: where the screened literature stops")})
    blk, why = conclusions(pkg_dir)
    if "concl" not in plan:
        actions.append({"block": "conclusion", "result": "not requested for this package"})
    elif blk is None:
        actions.append({"block": "conclusion", "result": f"not emitted: {why}"})
    else:
        actions.append({"block": "conclusion", "source": why,
                        "result": place(plan["concl"], blk, "## Conclusion")})
    if pid in GAP_SENTENCE and GAP_SENTENCE[pid].split(".")[0] not in text:
        text, note = insert_block(text, GAP_SENTENCE[pid], "## 2 ", "")
        actions.append({"block": "gap_sentence", "result": note})
    changed = text != orig
    if not dry and changed:
        pm.write_text(text, encoding="utf-8", newline="")
    actions.append({"block": "_file", "result": ("rewritten" if changed else "byte-identical, not rewritten")
                    + (" (dry run)" if dry else "")})
    return actions


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--paper", default="", help="restrict to one package id, e.g. P002")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")
    t0 = time.time()
    res = {"exp_id": "EXP-0100", "at": time.strftime("%Y-%m-%dT%H:%M:%S"), "dry_run": a.dry_run, "packages": {}}
    for pkg in sorted((ROOT / "papers").glob("P0*")):
        pid = pkg.name[:4]
        if a.paper and pid != a.paper:
            continue
        acts = apply_one(pkg, pid, a.dry_run)
        res["packages"][pid] = acts
        print(f"  {pid}: " + "; ".join(f"{x['block']} -> {x['result']}" for x in acts), flush=True)
    res["wallclock_sec"] = round(time.time() - t0, 1)
    out = OUT / f"EXP0100_manuscript_sections_{time.strftime('%Y%m%dT%H%M%S')}.json"
    out.write_text(json.dumps(res, indent=1, ensure_ascii=False), encoding="utf-8")
    print("wrote", out.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
