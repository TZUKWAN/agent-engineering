"""Spec §15: publish the figure and table plan each package actually executed, derived from the shipped files.

Section 15 asks every paper to *plan* at least eight things - a framework figure, a data/trajectory schematic, a main
result figure, a mechanism or grouping figure, a robustness/ablation figure, an error or case figure where applicable,
one key table and one full comparison table - and to generate them from scripts rather than typing numbers. Until now
the shipped packages satisfied the substance (3-7 vector figures and 5-23 generated tables each) but nothing in the
package said which artefact served which role, so the requirement could not be checked: `spec_completion_audit.py`
rightly counted §15 as open.

Two rules make this an audit rather than a relabelling exercise:

* items 1-6 of §15 are 图 and items 7-8 are 表, so a prose document can never serve a role here and a table can never
  serve a figure role - the candidate pool for each role is `figures/*.pdf` or `tables/*.csv`;
* a role with no artefact is printed as **no artefact serves this role**, never filled by "the next table in the
  folder". An earlier draft of this script fell back to `sorted(unused_tables)[-1]` for the comparison-table role,
  which labelled `table_run_cost.csv` - a cost log - as the paper's full comparison table. That is the kind of
  statement this file exists to prevent, so the fallback is gone and the two packages that genuinely had no
  comparison table now get one from `02_shared_code/plotting/`.

Assignment runs in two passes. The first locks an artefact to a role by the name its own generating script gave it
(`fig3_main_result`, `fig2_component_coverage`), longest-needle-wins, and a name that fits two roles equally well is
left unlocked. The second pass fills whatever is still empty from the artefact's own caption file, or - where a
package keeps none - the manuscript line that introduces it, or the header row of a table. Only unused artefacts are
preferred there; if every match is already taken the artefact is shared and the cell says so, because
`fig2_component_coverage` really is both a grouping view and part of the headline result, and reporting that role as
empty would misdescribe the package instead of the artefacts.

The file carries no generation timestamp: it is regenerated by every `reproduce.sh`, and a rebuild must reproduce it
byte for byte.

    python 02_shared_code/writing/export_figure_plan.py [--paper P004] [--check]
"""
from __future__ import annotations

import argparse, pathlib, re, sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = next(a for a in (HERE, *HERE.parents) if (a / "00_program_registry").is_dir())
PAPERS = sorted(p for p in (ROOT / "papers").glob("P0*") if p.is_dir())

# (role, what §15 asks for, which kind of artefact can serve it, the words that mark an artefact as serving it).
# Every needle below is a word that occurs in a name or header the package's own figure/table scripts chose, not a
# word invented here; §15's own four headings ("framework", "robustness / ablation", ...) are needles because the
# scripts name their files after the analysis they plot.
ROLES = [
    ("framework", "一张研究框架图", "figure",
     ["framework", "study design", "design", "overview"]),
    ("data schematic", "一张数据/trajectory 示意图", "figure",
     ["data_structure", "data_schematic", "trajectory", "schematic", "example", "data flow", "container",
      "reference_host", "presence", "censor", "structure", "schema", "corpus", "inventory", "source", "sample"]),
    ("main result", "一张主结果图", "figure",
     ["main_result", "headline", "primary", "criterion_validity", "level_ladder", "model_ladder", "ladder",
      "recoverab", "coverage", "shares", "effect", "verdict", "census", "result"]),
    ("mechanism / grouping", "一张机制/分组图", "figure",
     ["mechanism", "grouping", "component", "per_repositor", "per-repositor", "by_stage", "odds_ratio", "interchange",
      "concept", "confound", "gating", "stage", "transition", "dependence", "heatmap", "intervention", "group"]),
    ("robustness / ablation", "一张 robustness / ablation 图", "figure",
     ["robust", "ablation", "sensitivit", "perturb", "alternative", "second_matcher", "second_coder", "invariance",
      "reproducib", "truncation", "lexicon", "transfer"]),
    ("error taxonomy / case", "一张 error taxonomy / case figure（适用时）", "figure",
     ["error", "case", "false_negative", "taxonomy", "disagree", "conflict", "read_case", "failure"]),
    ("key table", "一张关键主表", "table",
     ["main", "primary", "key", "headline", "criterion_validity", "level_census", "ladder"]),
    ("full comparison table", "一张完整对比表", "table",
     ["comparison", "comparator", "benchmark", "sota", "coverage_matrix", "census", "inventory", "register",
      "matrix", "versus", "per_config", "config_comparison", "ladder", "appendix"]),
]
OPTIONAL = {"error taxonomy / case"}       # §15 marks item 6 "适用时" (where applicable)


def caption_of(a: pathlib.Path, pkg: pathlib.Path) -> str:
    """The artefact's own words: caption file, else the manuscript line that introduces it, else its header row."""
    if a.suffix == ".csv":
        try:
            return (a.read_text(encoding="utf-8", errors="replace").splitlines()[0] + " " + a.stem).lower()
        except IndexError:
            return a.stem.lower()
    c = a.with_suffix(".caption.txt")
    if c.is_file():
        return c.read_text(encoding="utf-8", errors="replace").lower()
    n = f"![{a.stem}]"
    m = re.search(r"fig\w*(\d+)", a.stem, re.I)
    label = f"figure {m.group(1)}." if m else None
    paper = (pkg / "paper.md")
    if paper.is_file():
        for ln in paper.read_text(encoding="utf-8", errors="replace").splitlines():
            if n in ln:
                return ln.lower()
            if label and ln.lower().startswith(label.lower()):
                return ln.lower()
    return a.stem.lower()


def _stated_reason(pkg: pathlib.Path, role: str):
    """A sentence from the package that already explains why this role has no artefact, quoted with its file.

    Only used when nothing serves the role. It searches the documents that carry the paper's own limits and verdicts,
    so the reason is the package's, not this script's; if none is found the plan says so plainly and the audit leaves
    §15 unmet rather than letting an empty cell pass as planned.
    """
    keys = {"framework": ["framework", "框架"], "data schematic": ["schematic", "structure", "示例", "结构"],
            "main result": ["main result", "primary", "主结果"],
            "mechanism / grouping": ["mechanism", "grouping", "机制", "分组"],
            "robustness / ablation": ["robust", "ablation", "sensitivit", "稳健", "消融"],
            "error taxonomy / case": ["error", "case", "适用", "错误", "案例"],
            "key table": ["key table", "主表"], "full comparison table": ["comparison", "对比", "完整表"]}.get(role, [])
    for f in (pkg / "limitations.md", pkg / "final_audit.md", pkg / "reviewer_attack.md", pkg / "appendix.md"):
        if not f.is_file():
            continue
        for sent in re.split(r"(?<=[。.!])\s+", f.read_text(encoding="utf-8", errors="replace")):
            low = sent.lower()
            # a markdown table row or a heading is not a reason; quoting one would also break this file's own table
            if "|" in sent or sent.lstrip().startswith("#"):
                continue
            if any(k.lower() in low for k in keys) and 40 < len(sent.strip()) <= 300:
                quote = re.sub(r"\s+", " ", sent.strip())
                return f"`{f.name}`: “{quote}”"
    return ""


def artefacts(pkg: pathlib.Path):
    figs = sorted((pkg / "figures").glob("*.pdf"))
    tabs = sorted((pkg / "tables").glob("*.csv"))
    return figs, tabs


def _best(needles, text):
    hits = [n for n in needles if n in text]
    return max(hits, key=len) if hits else ""


def plan_one(pkg: pathlib.Path) -> str:
    figs, tabs = artefacts(pkg)
    pool = {"figure": figs, "table": tabs}
    caps = {a: caption_of(a, pkg) for a in figs + tabs}

    # pass 1 - the name the generating script chose is the strongest evidence about what the artefact is. An
    # artefact is locked to a role only when that role is its single best name match; a name that fits two roles
    # equally well (fig1_coverage_heatmap is both a headline and a grouping view) is left for the caption pass.
    pref = {}
    for a in figs + tabs:
        kind = "figure" if a.suffix == ".pdf" else "table"
        ws = sorted(((len(_best(n, a.stem.lower())), r) for r, _q, k2, n in ROLES if k2 == kind), reverse=True)
        ws = [(w, r) for w, r in ws if w]
        pref[a] = ws
    locked, used = {}, set()
    for role, _ask, kind, _needles in ROLES:
        cands = sorted(((pref[a][0][0], a) for a in pool[kind] if a not in used and pref[a]
                        and pref[a][0][1] == role and (len(pref[a]) == 1 or pref[a][0][0] > pref[a][1][0])),
                       key=lambda x: (-x[0], x[1].name))
        if cands:
            locked[role] = [cands[0][1]]
            used.add(cands[0][1])

    rows = []
    for role, ask, kind, needles in ROLES:
        hits = list(locked.get(role, []))
        shared = False
        if not hits:                                        # pass 2 - the artefact's own caption or header
            free = [(a, caps[a]) for a in pool[kind] if a not in used and _best(needles, caps[a])]
            if free:
                hits = [a for a, _ in free[:2]]
            else:
                taken = [(a, caps[a]) for a in pool[kind] if _best(needles, caps[a])]
                hits = [a for a, _ in taken[:2]]
                shared = bool(hits)
            used.update(hits)
        cell = ", ".join(f"`{kind}s/{a.name}`" for a in hits)
        if shared and cell:
            cell += " (shared with a role above)"
        if not hits:
            stated = _stated_reason(pkg, role)
            if not stated and role in OPTIONAL:
                # §15 asks this one only 适用时, so the honest statement is what the package does instead, not a
                # placeholder that reads like work still owed. The alternative artefact is found by its own name.
                alt = [f"`{f.relative_to(pkg).as_posix()}`" for f in sorted(list((pkg / "tables").glob("*.csv"))
                                                                            + list(pkg.glob("*.md")))
                       if _best(needles, f.stem.lower())][:2]
                if alt:
                    stated = ("§15 marks this item 适用时, and the package reports the same analysis in "
                              + ", ".join(alt))
            tag = " (optional: §15 marks this one 适用时)" if role in OPTIONAL else ""
            cell = (f"**no {kind} serves this role**{tag}"
                    + (f" - {stated}" if stated.startswith("§15") else
                       (f" - the package's own reason: {stated}" if stated
                        else " and no reason is stated in the package")))
        rows.append((role, ask, kind, cell))

    unfig = [f for f in figs if f not in used]
    untab = [t for t in tabs if t not in used]
    extra = ""
    if unfig or untab:
        extra = ("\n\n## Shipped but not needed by any listed role\n\n"
                 + ", ".join(f"`figures/{f.name}`" for f in unfig)
                 + (", " if unfig and untab else "")
                 + ", ".join(f"`tables/{t.name}`" for t in untab)
                 + "\n\nThese are additional analyses the paper reports; the role list above is the spec's minimum, "
                   "not a budget.")
    svg = {f.stem for f in (pkg / "figures").glob("*.svg")}
    vector = sum(1 for f in figs if f.stem in svg)
    lines = "\n".join(f"| {r} | {a} | {k} | {c} |" for r, a, k, c in rows)
    return f"""# Figure and table plan - {pkg.name} (spec §15)

Generated by `02_shared_code/writing/export_figure_plan.py` from the files this package ships and the captions its
figure scripts wrote beside them, so the plan cannot drift from the delivered artefacts: it names no file that is not
in the package, and a role left unfilled is printed as unfilled.

{len(figs)} vector figures (PDF), {vector} of them also as SVG; {len(tabs)} generated tables. Nothing is typed by
hand: each artefact is written by a script under `scripts/` or `02_shared_code/` from `results_raw/`. Items 1-6 of
§15 ask for a figure and items 7-8 for a table, so only `figures/*.pdf` and `tables/*.csv` are candidates; a prose
report is never counted as a plan item.

| role | what §15 asks for | kind | the artefact that serves it |
|---|---|---|---|
{lines}{extra}

## Why an unfilled role is not a defect

§15 marks the error/case figure "适用时" (where applicable). Where a role has no artefact, the line above carries the
reason in the package's own words; a role with no artefact and no stated reason is printed as such, and
`spec_completion_audit.py` counts §15 unmet until it is either filled by a real artefact or explained by a
measurement.
"""


def unfilled(pkg: pathlib.Path):
    txt = plan_one(pkg)
    return [l.split("|")[1].strip() for l in txt.splitlines()
            if l.startswith("| ") and "no " in l and "serves this role" in l]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--paper", default="")
    ap.add_argument("--check", action="store_true", help="report the plan without writing it")
    a = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")
    bad = 0
    for pkg in PAPERS:
        if a.paper and pkg.name[:4] != a.paper:
            continue
        gaps = unfilled(pkg)
        if a.check:
            print(f"  {pkg.name[:4]}: unfilled={gaps or 'none'}")
        else:
            (pkg / "FIGURE_PLAN.md").write_text(plan_one(pkg), encoding="utf-8", newline="")
            print(f"  {pkg.name[:4]}: FIGURE_PLAN.md written (unfilled: {gaps or 'none'})")
        bad += len([g for g in gaps if g not in OPTIONAL])
    if not a.check:
        print(f"[figure-plan] roles with no artefact and no optional tag, across {len(PAPERS)} packages: {bad}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
