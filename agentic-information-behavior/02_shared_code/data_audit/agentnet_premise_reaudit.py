"""EXP-0073: re-audit the AgentNet premise, because a funnel decision was made on a false one.

The T004 decision doc says "AgentNet is not on this machine: the eight releases under `MATLABINTOKEN/datasets` are all
there is". That came from listing one directory. AgentNet is on this disk at `MATLABINTOKEN/data/raw/` - two JSONL
files, 22,625 task lines, 1.7 GB - and its step records carry `value.last_step_correct`. A topic (T029) is parked
partly on the wrong premise and another decision (T004's) cited it, so this step measures what the files support.

Design note, because the first version of this script was wrong for a reason worth recording: it parsed every line with
`json.loads` and had not finished one file after nine minutes on 1.7 GB. It was stopped and rewritten as two tiers:

  * **tier 1, exact over the whole file** - a byte-level stream scan counting the label markers, so label presence is a
    census rather than an estimate;
  * **tier 2, a documented random sample parsed properly** - to confirm *where* those markers sit (a step's `value`
    object, not some other structure), to get steps-per-task, and to look for any field declaring instruction
    provenance. Sample proportions carry Wilson intervals; the census counts do not need them.

The two tiers are reported side by side so a reader can see which claim rests on which measurement.

    python agentnet_premise_reaudit.py
"""
from __future__ import annotations

import json
import pathlib
import random
import re
import sys
import time
from collections import Counter

ROOT = pathlib.Path(__file__).resolve().parents[2]
RAW = ROOT.parent / "MATLABINTOKEN" / "data" / "raw"
OUT = ROOT / "results_raw" / f"EXP0073_agentnet_reaudit_{time.strftime('%Y%m%dT%H%M%S')}.json"
FILES = ["agentnet_ubuntu_5k.jsonl", "agentnet_win_mac_18k.jsonl", "meta_data_merged.jsonl"]
SAMPLE_N = 400
SEED = 20260920
MARKERS = {
    "last_step_correct_any": b'"last_step_correct"',
    "last_step_correct_true_spaced": b'"last_step_correct": true',
    "last_step_correct_true_compact": b'"last_step_correct":true',
    "last_step_redundant_any": b'"last_step_redundant"',
    "step_code_any": b'"code"',
    "step_observation_any": b'"observation"',
    "step_summary_any": b'"summary"',
}
PROV_MARKERS = [b'"human', b'"synthetic', b'"annotat', b'"wizard', b'"generated_by', b'"provenance',
                b'"source_type', b'"crowdwork']
PROV_WORDS = re.compile(r"\b(human[- ]written|human annotated|human generated|generated by (an? )?(llm|gpt|model)|"
                        r"synthetic(ally)? generated|annotator[- ]written|crowdworker|wizard of oz)\b", re.I)


def wilson(k, n, z=1.96):
    if not n:
        return [None, None]
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * (p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5 / d
    return [round(max(0.0, c - h), 4), round(min(1.0, c + h), 4)]


def line_offsets(path):
    """Byte offset of every line, from one streamed pass - cheap, and lets the sample avoid parsing the whole file."""
    offs, pos = [], 0
    with path.open("rb") as fh:
        for raw in fh:
            offs.append(pos)
            pos += len(raw)
    return offs


def tier1(path):
    counts = Counter({k: 0 for k in MARKERS})
    prov = Counter({k.decode(): 0 for k in PROV_MARKERS})
    lines = 0
    nbytes = 0
    with path.open("rb") as fh:
        for raw in fh:
            lines += 1
            nbytes += len(raw)
            for name, m in MARKERS.items():
                if m in raw:
                    counts[name] += raw.count(m)
            for k in PROV_MARKERS:
                if k in raw:
                    prov[k.decode()] += 1
    return {"lines": lines, "bytes": nbytes, "marker_occurrences": dict(counts),
            "provenance_marker_lines": dict(prov),
            "note": "counts are occurrences summed over lines; a line may hold several steps"}


def tier2(path, offs, rng):
    pick = sorted(rng.sample(range(len(offs)), min(SAMPLE_N, len(offs))))   # line INDICES; offs[i] is the byte offset
    top, stepv, prov_keys, prov_text, json_types = Counter(), Counter(), Counter(), Counter(), Counter()
    n_tasks = n_steps = n_with_label = 0
    steps_per_task = []
    # `offs` holds byte positions, so the file is read in binary mode and each sampled LINE INDEX is resolved
    # through it. Two bugs were measured here before this worked: seeking a text-mode handle to a byte offset, and
    # then using the sampled index itself as the offset - both land mid-record, and both looked like an empty corpus.
    with path.open("rb") as fh:
        for i in pick:
            fh.seek(offs[i])
            line = fh.readline()
            if not line.strip():
                continue
            if not line[:1] in (b"{", b"["):        # a JSONL record must start with a brace; catches a bad seek at once
                prov_keys["sample_line_does_not_start_with_brace"] += 1
                continue
            try:
                d = json.loads(line)
            except (json.JSONDecodeError, UnicodeDecodeError):
                prov_keys["unparseable_sample_line"] += 1
                continue
            n_tasks += 1
            json_types[type(d).__name__] += 1
            # keys are stringified: a line whose JSON value is a list would otherwise mix element types into the
            # Counter and make most_common() fail on comparing a list with a string
            top.update(map(str, d))
            for k in d:
                if re.search(r"human|synthetic|annotat|wizard|source|origin|proven|generat", k, re.I):
                    prov_keys[k] += 1
            traj = d.get("traj") or d.get("steps") or []
            steps_per_task.append(len(traj))
            has = 0
            for s in traj:
                n_steps += 1
                v = s.get("value") if isinstance(s.get("value"), dict) else {}
                stepv.update(map(str, v))
                if "last_step_correct" in v:
                    has += 1
                txt = " ".join(str(v.get(k, "")) for k in ("action_repr", "summary", "observation", "thought"))
                if PROV_WORDS.search(txt or ""):
                    prov_text["step_text_matches_provenance_phrase"] += 1
            n_with_label += int(has > 0)
    if not n_tasks:
        raise SystemExit(f"[e73] ABORT: the sample of {path.name} parsed 0/{len(pick)} lines. A zero here is a broken "
                         "read, not an empty corpus - refusing to publish an empty schema/provenance result.")
    return {"sampled_lines": len(pick), "parsed_tasks": n_tasks, "steps_in_sample": n_steps,
            "json_types_of_sampled_lines": dict(json_types),
            "tasks_with_any_last_step_correct": n_with_label,
            "share_of_tasks_with_label": round(n_with_label / max(1, n_tasks), 4),
            "wilson95_on_that_share": wilson(n_with_label, n_tasks),
            "mean_steps_per_task": round(sum(steps_per_task) / max(1, len(steps_per_task)), 2),
            "max_steps_in_sample": max(steps_per_task) if steps_per_task else 0,
            "top_level_keys": dict(top.most_common(25)), "step_value_keys": dict(stepv.most_common(25)),
            "provenance_like_keys": dict(prov_keys), "provenance_text_hits": dict(prov_text)}


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    rng = random.Random(SEED)
    res = {"exp_id": "EXP-0073", "at": time.strftime("%Y-%m-%dT%H:%M:%S"), "seed": SEED,
           "sample_n_per_file": SAMPLE_N,
           "premise_under_test": "AgentNet is not on this machine "
                                 "(docs/funnel_decision_T004_20260920.md)",
           "files": {}}
    tot_tasks = tot_label_lines = 0
    for name in FILES:
        p = RAW / name
        if not p.exists():
            res["files"][name] = {"exists": False}
            continue
        t0 = time.time()
        one = tier1(p)
        t1 = time.time()
        offs = line_offsets(p) if name != "meta_data_merged.jsonl" else line_offsets(p)
        two = tier2(p, offs, rng)
        res["files"][name] = {"exists": True, "tier1_exact_stream": one, "tier2_parsed_sample": two,
                              "tier1_seconds": round(t1 - t0, 1), "tier2_seconds": round(time.time() - t1, 1)}
        tot_tasks += one["lines"]
        tot_label_lines += one["marker_occurrences"]["last_step_correct_any"]
        print(f"  {name}: {one['lines']} lines, {one['marker_occurrences']['last_step_correct_any']} "
              f"last_step_correct markers ({res['files'][name]['tier1_seconds']}s scan, "
              f"{res['files'][name]['tier2_seconds']}s sample)", flush=True)

    agentnet = {k: v for k, v in res["files"].items() if k.startswith("agentnet")}
    label_lines = sum(v["tier1_exact_stream"]["marker_occurrences"]["last_step_correct_any"] for v in agentnet.values())
    res["totals"] = {"lines_all_files": tot_tasks, "agentnet_task_lines": sum(
        v["tier1_exact_stream"]["lines"] for v in agentnet.values()),
        "agentnet_label_markers": label_lines}
    res["premise_verdict"] = (
        "FALSE - AgentNet is on this disk and its step records carry the label" if label_lines else
        "NOT RESTORED - files present but no last_step_correct marker found")
    res["provenance_question_T004"] = {
        "per_file_keys": {k: v["tier2_parsed_sample"]["provenance_like_keys"] for k, v in res["files"].items()},
        "per_file_text_hits": {k: v["tier2_parsed_sample"]["provenance_text_hits"] for k, v in res["files"].items()},
        "stream_marker_lines": {k: v["tier1_exact_stream"]["provenance_marker_lines"]
                                for k, v in res["files"].items()},
    }
    res["consequence"] = {
        "T004": "the 'AgentNet is not on this machine' reason in that decision doc is withdrawn as a factual claim; "
                "T004's remaining grounds (only one release DECLARES the provenance construct; taxonomy columns are "
                "not provenance statements) are re-checked against AgentNet's own fields below rather than assumed",
        "T029": "its primary dataset exists with step-level labels, so T029 is not data-blocked; the outstanding gates "
                "are the novelty screen that never ran (EXP-0074) and the self-overlap check against the completed "
                "papers",
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(res, indent=1, ensure_ascii=False), encoding="utf-8", newline="")
    print(json.dumps({k: res[k] for k in ("totals", "premise_verdict", "provenance_question_T004")},
                     indent=1, ensure_ascii=False), flush=True)
    print("wrote", OUT.name)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
